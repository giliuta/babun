// Сайт возил в стартовом бандле словари всех шести языков (~690 КБ gzip), а
// человеку нужен один или ни одного: русский — исходный текст. Теперь словарь
// — отдельный чанк (`@babun/shared/i18n/dict-source.web.ts`), и код
// приложения запускается, только когда он пришёл: плагин перевода переводит
// строки уже при вычислении модулей, и словарь, пришедший позже, оставил бы
// их по-русски — первый кадр мигнул бы непереведённым.
//
// Язык сайта живёт в localStorage (`uiLocale`), и читать его можно раньше
// всего остального: хранилище приложения ему не нужно. Смена языка —
// перезагрузка страницы, то есть новый проход через этот файл.
//
// `@expo/metro-runtime` — ПЕРВЫМ, как в `expo-router/entry-classic`; следом
// `expo`: он ставит загрузчик чанков (`__loadBundleAsync`, `Expo.fx`). Без
// него `import()` словаря падает молча, и сайт открывается по-русски на любом
// языке. Кода приложения ни тот, ни другой не тянет.
import "@expo/metro-runtime";
import "expo";
import { uiLocale } from "@babun/shared/i18n/locale";
import { preloadDictionary } from "@babun/shared/i18n/runtime";

void preloadDictionary(uiLocale()).then(() => {
  require("expo-router/entry");
});
