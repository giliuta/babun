// Геометрия РЕШЁТКИ ВЫБОРА — одна на два блока: цвета (`ColorPicker`) и
// значки (`IconPicker`). Они всегда стоят в форме друг под другом (счёт, метка,
// категория), и разъехавшийся шаг между ними виден сразу: два набора точек в
// разной сетке читаются как два разных контрола вместо одного вопроса «как это
// выглядит в списке».
//
// Восемь в ряду — максимум, при котором на самом узком корпусе (320pt, минус
// поля карточки) клетка остаётся 32pt и кольцо выбора не обрезается.
//
// Высота клетки равна её ширине (338pt содержимого карточки ÷ 8 ≈ 42): при
// 38 шаг по горизонтали получался шире, чем по вертикали, и сорок точек
// читались столбиками, а не решёткой.
export const PICKER_COLUMNS = 8;
export const PICKER_CELL = 42;
