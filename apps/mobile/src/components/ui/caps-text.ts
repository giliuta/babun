/** КАПС — СТРОКОЙ, А НЕ `textTransform`. Android мерит ширину подписи по
 *  строчным буквам, а рисует заглавными: с трекингом последняя буква не
 *  влезала — «CLIEN» вместо «CLIENT», «FILE» вместо «FILES» (эмулятор,
 *  28.10). Строка приходит уже переведённой (плагин переводит литерал на
 *  месте), поэтому заглавные из неё не ломают словарь. */
export const capsText = (text: string): string => text.toUpperCase();
