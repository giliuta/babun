import DateTimePicker from "@react-native-community/datetimepicker";

// ДАТА И ВРЕМЯ — ОДНО ИМЯ КОМПОНЕНТА НА ВСЕ ПЛАТФОРМЫ.
//
// У @react-native-community/datetimepicker нет веб-реализации: общий фолбэк
// пакета возвращает `null` и пишет предупреждение в консоль. В браузере это
// значит пустое место там, где выбирают дату и время, — то есть приложение
// теряет свою главную функцию «назначить время».
//
// Здесь НЕ обёртка, а тот же самый компонент под другим именем: тип элемента
// не меняется, дерево и порядок монтирования тоже. Это важно ровно по одной
// причине — компактный нативный пикер запоминает дату, с которой родился;
// лишний слой между ним и родителем однажды уже воскрешал «1 янв. 1970 г.».
//
// Веб-реализация лежит рядом в DateTimeInput.web.tsx, Metro выбирает её сам —
// и через алиас `@/components/ui/DateTimeInput` тоже. Здесь раньше стоял
// запрет на алиас; он неверен: резолвер tsconfig-путей у Expo отдаёт
// найденный путь ОБРАТНО в резолвер Metro вместе с платформой
// (withMetroMultiPlatform → getOptionalResolver(context, platform)), так что
// `.web.tsx` подхватывается на общих основаниях. Проверено сборкой
// `expo export --platform web`: маркер из нативного файла в бандл не попал,
// стиль из веб-двойника попал.
export const DateTimeInput = DateTimePicker;
