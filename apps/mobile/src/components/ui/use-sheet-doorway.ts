import { useCallback, useState } from "react";
import { useFocusEffect } from "expo-router";

// ДВЕРЬ ИЗ ШТОРКИ НА СТРАНИЦУ — ШТОРКА УХОДИТ С ДОРОГИ И ВОЗВРАЩАЕТСЯ
// (владелец 2026-09-10: «нажал добавить операцию, выбрал категорию, нажимаю
// настройки — и оно открывается ЗА шторкой… я нажимаю назад, и оно должно
// перебрасывать на ту операцию, которую я создавал: может, я хотел в настройках
// что-то отредактировать и заново вернуться»).
//
// Что было. Лист операции — это `Modal`, отдельное окно поверх всего. Шестерёнка
// в шапке шторки выбора закрывала САМУ ШТОРКУ и делала `router.push`, но лист
// операции оставался открытым — и страница справочника уезжала ПОД него. На
// экране висел лист, за ним лежала недостижимая страница: ни править справочник,
// ни вернуться к операции.
//
// Что теперь. Дверь «паркует» лист: он уезжает вниз, страница открывается
// нормально, черновик при этом НЕ ТЕРЯЕТСЯ — состояние живёт в компоненте листа,
// а хозяин страницы держит его смонтированным. Возврат на страницу (`назад`)
// возвращает лист на место с тем же набранным.
//
// Почему не «второй шторкой поверх»: справочник — это полноценный экран со
// своим списком, свайпами и созданием строки; втиснутый в лист поверх листа, он
// становится третьим окном в кадре, из которого некуда нажать «назад».

/** Парковка листа на время ухода в справочник.
 *
 *  `visible={visible && !parked}` у своего `BottomSheet`, а дверь зовёт
 *  `open(() => router.push(...))`. */
export function useSheetDoorway(): {
  parked: boolean;
  open: (go: () => void) => void;
} {
  const [parked, setParked] = useState(false);

  // Возврат фокуса на страницу-хозяйку = мы вернулись из справочника. Именно
  // фокус, а не таймер: сколько человек пробудет в настройках, знать нельзя.
  useFocusEffect(
    useCallback(() => {
      setParked(false);
    }, []),
  );

  const open = useCallback((go: () => void) => {
    setParked(true);
    go();
  }, []);

  return { parked, open };
}
