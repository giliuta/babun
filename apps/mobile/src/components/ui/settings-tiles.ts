// Плитка `SettingsRow` — навигационный якорь: человек запоминает не подпись, а
// цветное пятно на своём месте («зелёное — выгрузка»). Пока хексы стояли
// литералами по экранам, якорь работал против себя: на одной странице настроек
// финансов встречались #2F6FD6, #3157A4 и кобальт бренда — ТРИ близких синих,
// которые глаз не различает как разные, но и не читает как один. Рядом жил
// #5B6678 — тот самый самостоятельный серый, который дизайн-система объявила
// удалённым.
//
// Поэтому пигментов ровно столько, сколько человек различает, и заводятся они
// здесь, а не в JSX:
//   • синий — ОДИН, и это кобальт бренда (`accent` в colors.ts). Второго
//     синего в продукте не существует;
//   • зелёный и фиолетовый — по одному: #1F7A44/#2E7D32 и #8E44AD/#AF52DE
//     стояли парами почти неразличимых оттенков на соседних экранах;
//   • серого здесь нет намеренно. Строка без своего цвета — `tile="neutral"`:
//     голый глиф чернилами, как у денежных экранов.
//
// Значение — обычная строка для пропа `tile`, поэтому словарь не тянет тему и
// зовётся вне компонента.
