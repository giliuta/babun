import type { ReactNode, Ref } from "react";
import type { TextInput } from "react-native";

export type FieldKeyboardType =
  | "phone-pad"
  | "email-address"
  | "url"
  | "default"
  | "decimal-pad"
  | "numbers-and-punctuation";

export interface FieldRowProps {
  label: string;
  value: string;
  placeholder: string;
  separated?: boolean;
  /** ПОДПИСЬ СЛЕВА КОЛОНКОЙ ЭТОЙ ШИРИНЫ (блок «Клиент»).
   *  Пример: «Телефон | +357 97 469 998», как «Настройки» iPhone.
   *  Значение — по левому краю своей колонки, линия между строками — от
   *  колонки значений. Нет — прежние виды строки. */
  column?: number;
  /** `decimal-pad` — деньги; `numbers-and-punctuation` — деньги, которые
   *  бывают отрицательными (остаток счёта в долге): минуса на цифровой
   *  клавиатуре нет ни в одной раскладке. */
  keyboardType?: FieldKeyboardType;
  /** «none» для @username и почты: клавиатура иначе пишет «@Artem_test» с
   *  заглавной, и в данных остаётся искажённый логин. «characters» — для
   *  номеров из букв и цифр (VAT, регистрационный). */
  autoCapitalize?: "none" | "sentences" | "words" | "characters";
  autoFocus?: boolean;
  live?: boolean;
  multiline?: boolean;
  valueColor?: string;
  tabular?: boolean;
  /** Значение крупнее — для имени и телефона (они и есть личность). */
  big?: boolean;
  /** Ярлык НЕ РИСУЕТСЯ над значением: и так понятно,
   *  что это телефон, а капс сверху лишний. Значение при этом остаётся
   *  подписанным для VoiceOver, а видимая подпись, если она нужна, живёт в
   *  хвосте строки — там, где различают номера. */
  hideLabel?: boolean;
  /** Ярлык СВЕРХУ мелким капсом, значение под ним и ПО ЛЕВОМУ краю.
   *  Так набирают текст: у правого выравнивания курсор стоит у кромки, а
   *  строка растёт влево — печатать в такое поле физически неудобно. */
  stacked?: boolean;
  trailing?: ReactNode;
  /** Ярлык тоже редактируем (доп. номера: «Жена», «Рабочий»). */
  onLabelPress?: () => void;
  /** Что показать вместо ПОДСКАЗКИ, когда значения нет: «Добавить».
   *  Инструкция в поле («Домофон 25, зелёная дверь…») читалась как введённый
   *  текст и объясняла то, что и так понятно из ярлыка строки. */
  addLabel?: string;
  /** Правка завершена (blur / Return / уход строки). Вызывающая сторона
   *  использует это, чтобы снять своё локальное состояние. */
  onEditEnd?: () => void;
  /** Каждый символ — БЕЗ записи в базу (в отличие от `live`). Нужен строкам,
   *  у которых хвост зависит от набранного: значок «открыть Telegram» обязан
   *  появиться, пока логин печатают, а не после ухода со строки. */
  onType?: (v: string) => void;
  /** Поле ввода наружу: серая главная кнопка ведёт курсор к первому
   *  незаполненному полю (карточка нового мастера). Поле смонтировано
   *  всегда только у `live` — у обычной строки ссылка пуста до правки. */
  inputRef?: Ref<TextInput>;
  /** Цвет набираемого текста: почта, не прошедшая проверку, краснеет прямо в
   *  поле. `valueColor` красит только показанное значение, не ввод. */
  inputColor?: string;
  /** Значение только показывается: почта приглашения — адрес, на который оно
   *  выписано, и сменить её значит позвать другого человека. */
  readOnly?: boolean;
  /** ПЛОТНАЯ СТРОКА ДЛЯ БЛОКОВ КЛИЕНТА И ЕГО ЛЮДЕЙ, чтобы не были слишком большими.
   *  Только у `stacked`: строка
   *  держит 44 точки вместо 60 — минимум Apple, — а подпись над значением
   *  мельче. Несколько таких строк без линий между ними читаются одной
   *  ячейкой, как контакт в iPhone: имя, под ним номер. */
  compact?: boolean;
  /** Долгое нажатие по строке (карточка клиента: «скопировать значение»).
   *  Работает только вне ввода — в открытом поле долгое нажатие принадлежит
   *  самому полю (лупа, «Вставить»), и отбирать его нельзя. Строке только
   *  для чтения оно тоже доступно: скопировать можно и то, что не правится. */
  onLongPress?: () => void;
  /** Без системного «Скопировать» в открытом поле: клиент чужой компании не
   *  выносится из приложения. Править значение можно. */
  noCopy?: boolean;
  /** ЖИВОЕ ПОЛЕ, ЗНАЧЕНИЕ КОТОРОГО ВЛАДЕЛЕЦ ПЕРЕПИСЫВАЕТ ПОСРЕДИ ВВОДА (имя
   *  нового клиента: вставили «Мария +357 99…» — номер уехал в телефон, в
   *  имени осталось «Мария»). Без флага набранный текст сверяется со
   *  значением только после ухода с поля, и вставка висела бы в имени до
   *  blur, а следующая буква вернула бы номер обратно. Не включать у полей с
   *  форматированием на лету (номер): текст прыгал бы под пальцем. */
  followValue?: boolean;
  /** ЧИСТКА ПОД ПАЛЬЦЕМ для поля со своим алфавитом (буквы серии номера:
   *  латиница заглавными и цифры). Отсечённое не появляется в поле вовсе —
   *  родитель, получив то же значение, перерисовкой его бы не убрал. */
  sanitize?: (v: string) => string;
  /** С ЧЕГО НАЧИНАЕТСЯ ПУСТОЕ ПОЛЕ — код страны номера («+357 »).
   *  Код —
   *  часть набранного: его стирают и вписывают свой. Оставленный один код
   *  номером не считается — строка сохраняется пустой. */
  seed?: string;
  onSave: (v: string) => void;
}
