// РОЛЬ В СТРОКЕ НЕ НАЗЫВАЕТСЯ (владелец 15.09: «роль уберём, она в целом нам
// не нужна»): строка говорит, что человек видит и может, а не как это
// зовётся. Роль нужна только, чтобы выбрать одну из двух строк.
//
// МЕСТО — ИЗ ПРИКРЕПЛЕНИЙ, А ДОСТУП ДО ЭТАПА 2 — ИЗ `calendar_members` (006,
// 14.09). Сейчас они совпадают: приём приглашения пишет оба списка
// (`d760ff11`), а `set_member_calendars` приложение не зовёт нигде. Экран,
// который начнёт менять прикрепления, до этапа 2 обязан либо запереть их, как
// уровни, либо перевести эту строку на `granted_calendars` из `list_members`.
// Иначе владелец открепит «Команду 1», строка скажет «во всех календарях», а
// человек по-прежнему будет видеть только её.

const TAIL = "Эти положения начнут действовать, когда включим права по блокам.";

function where(calendarNames: readonly string[]): string {
  // Без прикреплений диспетчер без прав по календарям видит всю компанию.
  if (calendarNames.length === 0) return "во всех календарях";
  const quoted = calendarNames.map((name) => `«${name}»`).join(", ");
  return calendarNames.length === 1 ? `в календаре ${quoted}` : `в календарях ${quoted}`;
}

/** `calendarNames` — имена прикреплённых календарей; `null`, если назвать их
 *  нельзя (список календарей не пришёл или календарь в архиве). Тогда строка
 *  говорит только то, что известно наверняка. */
export function roleAccessNotice(
  role: string | null,
  calendarNames: readonly string[] | null,
): string {
  if (calendarNames === null) return TAIL;
  if (role === "dispatcher") {
    return `Сейчас видит записи, клиентов и телефоны ${where(calendarNames)}. ${TAIL}`;
  }
  if (role === "master") {
    // С 15.09 у принявшего приглашение мастера есть карточка: статус и заметку
    // записей своего календаря он меняет сам (`invited_master_gets_card`).
    const records = calendarNames.length === 0 ? "свои записи" : `записи ${where(calendarNames)}`;
    return `Сейчас видит ${records} без сумм, меняет в них статус и заметку. ${TAIL}`;
  }
  return TAIL;
}
