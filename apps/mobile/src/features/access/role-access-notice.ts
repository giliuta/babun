const TAIL = "Эти положения начнут действовать, когда включим права по блокам.";

function where(calendarNames: readonly string[]): string {
  // Без прикреплений диспетчер без прав по календарям видит всю компанию.
  if (calendarNames.length === 0) return "во всех календарях";
  const quoted = calendarNames.map((name) => `«${name}»`).join(", ");
  return calendarNames.length === 1 ? `в календаре ${quoted}` : `в календарях ${quoted}`;
}

/** `calendarNames` — имена прикреплённых календарей; `null`, если назвать их
 *  нельзя (список календарей не пришёл или календарь в архиве). Тогда строка
 *  говорит только то, что известно наверняка. */
export function roleAccessNotice(
  role: string | null,
  roleLabel: string | null,
  calendarNames: readonly string[] | null,
): string {
  if (!roleLabel || calendarNames === null) return TAIL;
  if (role === "dispatcher") {
    return `Сейчас доступ задаёт роль «${roleLabel}»: записи, клиенты и телефоны ${where(calendarNames)}. ${TAIL}`;
  }
  if (role === "master") {
    const place = calendarNames.length === 0 ? "" : ` ${where(calendarNames)}`;
    return `Сейчас доступ задаёт роль «${roleLabel}»: свои записи${place}, без сумм. ${TAIL}`;
  }
  return TAIL;
}
