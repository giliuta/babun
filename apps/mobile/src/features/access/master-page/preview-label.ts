// КНОПКА ЗЕРКАЛА НАЗЫВАЕТ ЧЕЛОВЕКА, А НЕ ЕГО РОД. «Посмотреть его глазами»
// стояло и под партнёром-женщиной; имя рода не требует и сразу говорит,
// чьи права откроются. Без имени (черновик) — «партнёр», слово продукта.
export function previewLabel(name: string | null | undefined): string {
  const who = (name ?? "").trim();
  return who ? `Посмотреть как ${who}` : "Посмотреть как партнёр";
}
