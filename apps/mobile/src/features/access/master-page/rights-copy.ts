/** Фраза последствия для положения блока. Незнакомый ключ или положение —
 *  слово положения: экран обязан работать и на блоке, которого ещё нет в
 *  словаре (реестр живёт на сервере и может обогнать сборку). */
export function levelSentence(blockKey: string, level: AccessLevel): string {
  return SENTENCES[blockKey]?.[level] ?? LEVEL_WORD[level];
}

/** Слово на сегменте. Короче, чем в реестре: «Из его календарей» в трети
 *  ширины не помещается, а фраза под названием и так говорит правило целиком. */
export const SEGMENT_WORD: Record<AccessLevel, string> = {
  off: "Не видит",
  read: "Видит",
  write: "Меняет",
  own: "Его",
  all: "Все",
};

/** Слово сегмента для строки блока. Блок-ДЕЙСТВИЕ («Не может / Может»:
 *  новые записи, перенос, отмена, цвет) видеть нечего — он про то, может ли
 *  человек это сделать. «Отменять и удалять — Не видит» читалось как
 *  «запись не видна», а значит другое (STORY-088). */
export function segmentWord(levels: readonly AccessLevel[], level: AccessLevel): string {
  const isAction = levels.length === 2 && levels[0] === "off" && levels[1] === "write";
  if (isAction) return level === "write" ? "Может" : "Не может";
  return SEGMENT_WORD[level];
}

/** Есть ли у блока свои фразы — нужно тесту и сторожу словаря. */
export function hasSentences(blockKey: string): boolean {
  return blockKey in SENTENCES;
}

// СТРАНИЦА ПОКАЗЫВАЕТ ТОЛЬКО ТО, ЧТО СЕРВЕР ПРАВДА ДЕРЖИТ.
//
// В реестре 52 блока (21.09, STORY-084: «каждый блок — свой переключатель»,
// и сама запись разобрана на блоки её формы),
// а сторожей имеют семь: `record.payment`, `finance.operations`,
// `finance.accounts`, `finance.debts`, `clients`, `clients.scope`,
// `clients.contacts`. Остальные сервер не проверяет и — что хуже — не
// отказывает при записи: владелец ставил «Мастера: Меняет», видел слово и не
// получал ничего. Это ложное обещание безопасности (AGENTS.md, правило 10).
//
// Поэтому строку даёт только живой блок. Список не зашит: живость приходит из
// реестра, и как только блок оживёт на сервере, строка появится сама.
export function offeredBlocks(blocks: readonly AccessBlock[]): AccessBlock[] {
  return blocks.filter((block) => block.live && !block.ownerOnly);
}
