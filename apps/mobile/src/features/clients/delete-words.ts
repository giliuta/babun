// Удаление клиента записи не трогает: будущие остаются в календаре — с его
// именем и пометкой «удалён». Вопрос об этом молчал, и после удаления
// человек находил в календаре записи, о которых не думал.

/** Строка о будущих записях — вторым абзацем вопроса; нет записей — пусто. */
export function upcomingRecordsNote(count: number): string {
  if (count <= 0) return "";
  const line = `У клиента будущих записей: ${count} — они останутся в календаре.`;
  return `\n\n${line}`;
}
