import { useMemo } from "react";
import { clientMemberships, type Client } from "@babun/shared/local/clients";
import { ClientPickerSheet } from "@/features/clients/ClientPickerSheet";

// ШТОРКА СВЯЗИ — ТА ЖЕ ШТОРКА КЛИЕНТА, ТОЛЬКО С ГОТОВЫМ ВОПРОСОМ (STORY-086).
//
// Второй копии выбора клиента в продукте быть не должно: их уже было две, и
// они разошлись до трёх высот строки и трёх полей поиска (см. заголовок
// `select-rows.tsx`). Поэтому здесь ни одной строки вёрстки — только то, чего
// `ClientPickerSheet` знать не обязан: КТО СПРАШИВАЕТ и ЧТО он уже решил.
//
// Дверь приносит с собой ответ на половину вопроса. «Добавить жильца» в листе
// Виллы 5 уже знает и роль («жилец»), и место — спрашивать их вторым шагом
// значит завести «лишний этап», который владелец 2026-09-21 снял с выбора НДС
// восемь раз подряд. Поэтому роль и место едут вместе с выбранным человеком
// одним объектом `LinkDraft`, а писатель получает готовую связь.
//
// Заголовок тоже от двери: «Кто это» на карточке человека и «Кто здесь живёт»
// в листе объекта — один вопрос, заданный словами того места, где его задают.
// Имя объекта в заголовок не склеивается: это его тип в именительном («Дом»),
// и «Кто живёт в Дом» читалось бы поломкой (разбор — у двери на странице).

/** Что дверь уже решила за человека: кем он будет и где. */
export interface LinkDraft {
  /** Роль своими словами; пустая законна (владелец 2026-09-21 — без чипов и
   *  без словаря). Дверь объекта решает её вопросом — «жилец»; дверь людей
   *  на карточке ответа не знает и оставляет пусто (ТЗ, «что НЕ делаем» 7). */
  role: string;
  /** Объект карточки-группы, если место названо дверью («Вилла 5»). */
  locationId?: string;
}

export function LinkPickerSheet({
  visible,
  title,
  group,
  role = "",
  locationId,
  clients,
  linkFor,
  onPick,
  onCreate,
  onClose,
  onExited,
}: {
  visible: boolean;
  /** Вопрос двери — «Кто это» / «Кто здесь живёт». */
  title: string;
  /** Карточка, К КОТОРОЙ привязывают. Из неё же берётся запрет круга: связь
   *  живёт у члена, поэтому карточки, членом которых состоит сама группа,
   *  предлагать нельзя — иначе двое окажутся друг у друга и в «Людях», и в
   *  строке «чей он» (решение 4). */
  group: Client;
  /** Роль по умолчанию от двери. */
  role?: string;
  /** Место от двери — объект группы. */
  locationId?: string;
  /** Готовый список. Нет — шторка берёт весь справочник сама. */
  clients?: Client[];
  /** «жилец · Наталья · Вилла 5» под именем: видно, что человек уже чей-то. */
  linkFor?: (client: Client) => string | undefined;
  onPick: (client: Client, link: LinkDraft) => void;
  /** Человека в справочнике нет: набранное в поиске разбирается на имя и
   *  номер (это умеет сама шторка), а связь едет с ним в черновик — клиент и
   *  связь записываются ОДНОЙ записью в базу (ТЗ, «Когда пишется»). */
  onCreate?: (prefill: { name?: string; phone?: string }, link: LinkDraft) => void;
  onClose: () => void;
  /** Шторка полностью ушла и её окно снято — только теперь можно открывать
   *  следующее (страницу черновика, другой лист). */
  onExited?: () => void;
}) {
  // Карточки, членом которых состоит сама группа. Считается из СВЕЖЕЙ строки
  // группы, а не запоминается на открытии: связь могли снять соседним жестом.
  const excludeIds = useMemo(
    () => clientMemberships(group).map((m) => m.group_id),
    [group],
  );
  // Связь неизменна, пока дверь не сменилась: новый объект на каждый рендер
  // заставлял бы получателя перезаписывать черновик.
  const link = useMemo<LinkDraft>(() => ({ role, locationId }), [role, locationId]);

  return (
    <ClientPickerSheet
      visible={visible}
      title={title}
      // Человека здесь ИЩУТ по имени: список недавних на этот вопрос не
      // отвечает, и тап в поле стоял бы между вопросом двери и ответом.
      autoFocusSearch
      clients={clients}
      excludeId={group.id}
      excludeIds={excludeIds}
      linkFor={linkFor}
      onSelect={(client) => onPick(client, link)}
      onCreate={onCreate ? (prefill) => onCreate(prefill, link) : undefined}
      onClose={onClose}
      onExited={onExited}
    />
  );
}

export default LinkPickerSheet;
