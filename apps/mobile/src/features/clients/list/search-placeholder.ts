import { pluralPhraseRu } from "@babun/shared/common/utils/plural-ru";

// ЧИСЛО КЛИЕНТОВ — В ПОЛЕ ПОИСКА (выбор владельца): «Поиск среди 248
// клиентов». Число — ровно то, что видно в списке: выбранная команда («Все» —
// все) с включёнными фильтрами. Пока список едет — без числа: «0» читался бы
// как «клиентов нет». Ноль — тоже без числа: пустоту говорит сам список
// своим пустым состоянием, поле поиска её не дублирует.
//
// ОДНА ФРАЗА НА ЧИСЛО ОДИН, ДРУГАЯ НА ОСТАЛЬНЫЕ (`pluralPhraseRu`): «среди 1
// клиента», «среди 2 клиентов» — по-русски родительный, и ключ словаря один
// на одну форму, иначе «Search 1 clients».

export function clientsSearchPlaceholder(count: number | null): string {
  if (count == null || count <= 0) return "Поиск";
  return pluralPhraseRu(count, `Поиск среди ${count} клиента`, `Поиск среди ${count} клиентов`);
}
