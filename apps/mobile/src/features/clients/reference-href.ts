import { usePathname } from "expo-router";

// КУДА ВЕДЁТ ШЕСТЕРЁНКА СПРАВОЧНИКА — РЕШАЕТ МАРШРУТ, А НЕ ФЛАГ.
//
// Справочники карточки клиента («Типы объектов», «Карты для маршрута»,
// «Способы связи») живут ВНУТРИ вкладки «Клиенты». Открытые из ЗАПИСИ — а она
// маршрут корневого стека НАД табами — они кладут поверх неё вторую копию
// табов: «назад» приводит на список клиентов, и запись со всем набранным
// исчезает. Владелец 2026-09-04, поймав это на типах объектов: «жму назад — и
// закрывается; так не должно быть, назад всегда должно перекидывать на
// запись, запись просто так не может закрыться».
//
// Поэтому у записи есть свои сиблинги тех же экранов (`app/book/*`), и любой
// лист, вызванный из записи, ведёт туда. Решение по `usePathname()`, а не по
// пропу-флагу: флаг пришлось бы протаскивать через пять листов и он пережил
// бы уход с экрана; маршрут же всегда говорит правду о том, где мы сейчас.
//
// Карточка клиента, открытая из записи, живёт по `/book/client` — её листы
// (способы связи) попадают под то же правило автоматически.
export function useReferenceHref() {
  const inBooking = usePathname().startsWith("/book");
  return {
    objectTypes: inBooking
      ? ("/book/object-types" as const)
      : ("/clients/object-types" as const),
    maps: inBooking ? ("/book/maps" as const) : ("/clients/maps" as const),
    channels: inBooking
      ? ("/book/channels" as const)
      : ("/clients/channels" as const),
  };
}
