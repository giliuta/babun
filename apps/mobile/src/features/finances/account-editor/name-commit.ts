// ИМЯ СЧЁТА ПРАВИТСЯ ПРЯМО В СТРОКЕ и уходит на сервер, когда из поля ушли.
//
// Разбор багов счетов 2026-09-15: набранное стиралось сразу после отправки, и
// на весь круг по сети в строке снова стояло старое имя; а если сохранение
// падало, от набранного оставался только алерт. Поэтому черновик живёт до
// ответа, а после успеха строка держит отправленное имя, пока список счетов не
// перечитается.

/** Длина имени счёта — у поля в настройках и в листе создания. Имя стоит в
 *  плитке «Финансов», в переводе и в оплате; длиннее оно там не читается, а
 *  у базы своего предела нет. */
export const ACCOUNT_NAME_MAX = 40;

/** Имя отправлено и принято; `from` — каким оно было в списке до отправки. */
export interface SentName {
  sent: string;
  from: string;
}

/** Что писать на сервер, когда из поля ушли. `null` — писать нечего: пустое имя
 *  (счёт без названия не различить ни в переводе, ни в оплате) или то же самое. */
export function nameToSend(draft: string | null, current: string): string | null {
  if (draft === null) return null;
  const trimmed = draft.trim();
  return trimmed && trimmed !== current ? trimmed : null;
}

/** Какое имя стоит в строке. Отправленное держится, только пока список не
 *  сдвинулся с прежнего имени: пришло новое (наше или чужое) — показываем его. */
export function shownName(
  draft: string | null,
  sent: SentName | null,
  current: string,
): string {
  if (draft !== null) return draft;
  return sent && current === sent.from ? sent.sent : current;
}

/**
 * Что писать, когда из поля ушли, — сравнивая с ИМЕНЕМ В СТРОКЕ, а не со
 * списком (разбор 2026-09-15). Переименовали «Касса» → «Касса 2», и пока
 * список не перечитан, вернули «Касса»: сравнение со старым списком считало
 * это «ничего не поменялось», черновик молча стирался, в строке оставалось
 * «Касса 2», и оно же доезжало с рефетчем.
 */
export function nameToCommit(
  draft: string | null,
  sent: SentName | null,
  current: string,
): string | null {
  return nameToSend(draft, shownName(null, sent, current));
}
