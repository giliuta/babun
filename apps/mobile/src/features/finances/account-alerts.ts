// ТЕКСТЫ АЛЕРТОВ ПО СЧЕТАМ — ОДИН ИСТОЧНИК НА ПРОДУКТ (живой аудит 2026-08-10,
// раздел D, таблица переписанных текстов).
//
// Почему модулем, а не строками по месту: тексты закрытия счёта и удаления
// перевода жили в ДВУХ копиях каждый и уже разъехались хвостом фразы —
// человек читал разное предупреждение об одном и том же действии, в
// зависимости от того, с какого экрана пришёл.
//
// Правила текстов (оттуда же): заголовок — короткий вопрос или состояние;
// тело — ПОСЛЕДСТВИЕ, а не оправдание; кнопка — глагол действия («Закрыть» в
// системном алерте iOS читается как «закрыть это окно», поэтому глагол всегда
// с существительным); «Отмена» первой; кнопок «ОК» и «Да» в продукте нет.

import { money, moneySign } from "@babun/shared/common/utils/money";

export interface AlertText {
  title: string;
  message: string;
  /** Подпись деструктивной кнопки. Без неё диалог — просто сообщение. */
  confirm?: string;
}

/** Мягкое закрытие: обратимо и сохраняет историю — об этом и говорим.
 *
 *  ЕСЛИ ЗАКРЫВАЮТ ОСНОВНОЙ СЧЁТ — СКАЗАТЬ, КУДА ПЕРЕЕДУТ ДЕНЬГИ (аудит счетов
 *  2026-09-10). Флаг «основной» снимался молча, и оплаты бригадира начинали
 *  падать на первый попавшийся счёт по порядку — человек узнавал об этом уже
 *  по деньгам, а не по тексту. */
export function closeAccountAlert(
  name: string,
  successorName?: string | null,
): Required<AlertText> {
  const tail = successorName
    ? ` Это основной счёт команды — основным станет «${successorName}».`
    : "";
  return {
    title: "Закрыть счёт?",
    message:
      `«${name}» исчезнет из форм оплаты — принимать на него деньги будет `
      + "нельзя. Операции и остаток останутся в истории, счёт можно открыть "
      + `снова.${tail}`,
    confirm: "Закрыть счёт",
  };
}

/** «Скрыть» на странице «Счета» — то же мягкое закрытие, но словом свайпа
 *  (владелец 2026-09-15: «влево свайп — скрыть»). Свайп говорил «Скрыть», а
 *  вопрос и тост — «Закрыть счёт»: два глагола на одно действие (ревью
 *  2026-09-15). Куда пропадает счёт, сказано прямо: в «Закрытые счета», и
 *  вернуть его можно там же. */
export function hideAccountAlert(
  name: string,
  successorName?: string | null,
): Required<AlertText> {
  const tail = successorName
    ? ` Это основной счёт команды — основным станет «${successorName}».`
    : "";
  return {
    title: "Скрыть счёт?",
    message:
      `«${name}» уйдёт в «Закрытые счета» и исчезнет из форм оплаты. `
      + `Операции и остаток останутся в истории, вернуть счёт можно там же.${tail}`,
    confirm: "Скрыть счёт",
  };
}

/**
 * Жёсткое удаление: счёт без единой операции. Слово «навсегда» обязательно.
 *
 * СУММУ НАЗЫВАЕМ, ЕСЛИ ОНА ЕСТЬ. «Не прошло ни одной операции» человек читает
 * как «там пусто», но остаток на начало операцией не является: счёт, заведённый
 * с €500 и ни разу не тронутый, уносит эти €500 из «Всего денег» молча.
 */
export function deleteAccountAlert(
  name: string,
  balance = 0,
): Required<AlertText> {
  const hasMoney = moneySign(balance) !== 0;
  return {
    title: "Удалить счёт?",
    message: hasMoney
      ? `По «${name}» не прошло ни одной операции, но на нём записано `
        + `${money(balance)}. Удаляем насовсем — эта сумма исчезнет и из `
        + "«Всего денег». Восстановить будет нечего."
      : `По «${name}» не прошло ни одной операции — удаляем насовсем, `
        + "восстановить будет нечего.",
    confirm: "Удалить счёт",
  };
}

/**
 * Предусловие закрытия: на счёте остались деньги. Текст называет СУММУ и
 * последствие («пропадут из общего остатка»), а не запрет.
 *
 * `canTransfer` — есть ли куда переводить: у тенанта с единственным счётом
 * законной пары может не быть вовсе, и обещать кнопку «Перевести» в такой
 * ситуации нельзя.
 */
export function accountNotEmptyAlert(
  name: string,
  balance: number,
  canTransfer: boolean,
): AlertText {
  const amount = money(balance);
  // МИНУС — НЕ «ОСТАЛИСЬ ДЕНЬГИ». Переводить с такого счёта нечего, и кнопка
  // «Перевести −€120» отбилась бы проверкой суммы. Совет обратный: сначала
  // провести приход, и только потом закрывать.
  if (moneySign(balance) < 0) {
    // МИНУС — ЭТО ТОЖЕ ВЫХОД, А НЕ ТУПИК (аудит счетов 2026-09-10). Раньше
    // здесь был только текст «проведите приход», без единой двери: человек шёл
    // искать перевод сам и вручную ставил направление. Кнопка есть, когда
    // деньги в компании вообще есть — иначе переводить действительно нечего.
    return {
      title: "Счёт в минусе",
      message: canTransfer
        ? `На «${name}» ${amount}. Закрыть можно только счёт с нулём — `
          + "пополните его с другого счёта или проведите приход."
        : `На «${name}» ${amount}. Закрыть можно только счёт с нулём — сначала `
          + "проведите приход на эту сумму.",
      confirm: canTransfer ? "Пополнить счёт" : undefined,
    };
  }
  return {
    title: "На счёте остались деньги",
    message: canTransfer
      ? `На «${name}» ${amount}. Закрыть можно только пустой счёт — иначе эти `
        + "деньги пропадут из общего остатка. Переведите их на другой счёт или "
        + "спишите операцией."
      : `На «${name}» ${amount}. Закрыть можно только пустой счёт. Спишите `
        + "остаток операцией.",
    confirm: `Перевести ${amount}`,
  };
}

// Открытия счёта в этом списке НЕТ намеренно: оно обратимо, и продукт
// спрашивает про него не ДО действия, а после — тостом с «Отменить» (архив) и
// строкой в настройках счёта. Вопрос перед обратимым действием читают как
// формальность.

/**
 * Удаление перевода. Заголовок — ВОПРОС: «Перевод между счетами» это имя
 * сущности, а VoiceOver читает заголовок первым и обрывался на нём.
 */
export function deleteTransferAlert(): Required<AlertText> {
  return {
    title: "Удалить перевод?",
    message:
      "Перевод состоит из двух операций и меняется только целиком. Обе "
      + "исчезнут, остатки обоих счетов вернутся к прежним.",
    confirm: "Удалить перевод",
  };
}

