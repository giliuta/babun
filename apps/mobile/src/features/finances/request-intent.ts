// КЛЮЧ НАМЕРЕНИЯ ЗАПИСИ ДЕНЕГ — «тот же request_id только для того же».
//
// Повтор после потерянного ответа обязан прийти с ТЕМ ЖЕ id: строка уже
// могла лечь, и дубликат ключа читается как успех — деньги не задваиваются.
// Но успех этот — про ПЕРВУЮ попытку: репозиторий возвращает уже записанную
// строку, не сверяя её с новой. Поправил человек сумму, счёт или день перед
// повтором — с прежним id он увидел бы «добавлено», а на счёте осталась бы
// старая сумма. Поэтому id живёт, пока не изменилось ни одно поле черновика.
//
// Модуль без зависимостей: генератор id передаётся снаружи, и логика
// проверяется тестом без окружения RN.

/** Память «ключ → id» на одно намерение: повтор без правок — тот же id,
 *  правка любого поля — новый ключ и новый id. */
export function createRequestIntent(uuid: () => string): {
  idFor(key: string): string;
  done(): void;
} {
  let current: { key: string; id: string } | null = null;
  return {
    idFor(key) {
      if (current?.key !== key) current = { key, id: uuid() };
      return current.id;
    },
    /** Записано или лист открыт заново — намерение закрыто: следующее
     *  получит свежий id даже с теми же полями. */
    done() {
      current = null;
    },
  };
}

/** Ключ черновика: все поля, что уходят на сервер, в порядке имён — от
 *  порядка сборки объекта ключ не зависит. */
export function draftIntentKey(draft: Record<string, unknown>): string {
  return JSON.stringify(
    Object.keys(draft)
      .sort()
      .map((key) => [key, draft[key] ?? null]),
  );
}
