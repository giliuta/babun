// «ОТМЕНИТЬ» УДАЛЕНИЕ ВОЗВРАЩАЕТ СЧЁТ ТАКИМ, КАКИМ ЕГО УДАЛИЛИ.
//
// Сервер при восстановлении всегда открывает счёт (`account_trash_rules`:
// «Восстановить» — обычный открытый счёт), и закрыть его тем же запросом
// нельзя — триггер перебивает флаг. Для «Вернуть» из «Удалённых счетов» это
// верно, а «Отменить» в тосте обещает отмену одного жеста: закрытый счёт,
// удалённый и тут же возвращённый, вставал бы в список открытых и в выбор
// счёта операции. Поэтому закрытый закрывается снова вторым запросом.

/** Отменить удаление `target` — счёта в том виде, в каком его удаляли. */
export async function undoAccountTrash(
  target: { id: string; is_active: boolean },
  ops: { restore(id: string): Promise<void>; close(id: string): Promise<void> },
): Promise<void> {
  await ops.restore(target.id);
  if (!target.is_active) await ops.close(target.id);
}
