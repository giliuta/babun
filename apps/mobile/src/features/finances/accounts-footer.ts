//
// Владелец 2026-09-15: «планирую убрать кнопку „Добавить счёт“ и вместо неё
// сделать „Сделать перевод“; „Добавить счёт“ появляется тогда, когда нет вообще
// ни одного счёта». Создание живёт на странице «Счета» за ползунками шапки (там
// внизу своя кнопка «Добавить счёт»), поэтому футер «Финансов» — про движение
// денег:
//   • у команды чипа нет ни одного счёта → «Добавить счёт», шторка прямо на
//     «Финансах»: плиток нет, переводить нечего и не с чего;
//   • счета есть → «Сделать перевод»; выбрана плитка — перевод С НЕЁ: счёт уже
//     назван тапом, второй раз его не спрашиваем;
//   • счёт у компании всего один → кнопка всё равно «Сделать перевод» (так
//     сказал владелец), но шторка не открывается: переводить некуда, и тап
//     отвечает одной строкой, а не пустым листом.
//
// ВТОРОЙ СЧЁТ ИЩЕТСЯ ПО КОМПАНИИ, А НЕ ПО КОМАНДЕ ЧИПА: деньги ходят между
// командами, и «сдать выручку на счёт другой команды» — обычный перевод.
//
// Выбор считается только ВИДИМЫЙ. Выбранный счёт мог уйти в другую команду
// или закрыться — плиток его уже нет, и перевод «с невидимого» предлагал бы
// то, чего на экране нет.

export type AccountsFooterAction =
  | { kind: "create" }
  /** `fromId: null` — источник выберут в самой шторке перевода. */
  | { kind: "transfer"; fromId: string | null }
  /** Счёт у компании один: кнопка «Сделать перевод», тап объясняет. */
  | { kind: "needs-second" };

/** Что говорит тап по переводу, когда второго счёта нет. */
export const TRANSFER_NEEDS_SECOND = "Для перевода нужен второй счёт";

export function accountsFooterAction({
  selectedId,
  shown,
  company,
}: {
  /** Выбор экрана (адрес или тап), как есть. */
  selectedId: string | null;
  /** Счета, которые сейчас стоят плитками (срез команды). */
  shown: readonly { id: string }[];
  /** Все открытые счета компании: деньги ходят между командами. */
  company: readonly { id: string }[];
}): AccountsFooterAction {
  if (shown.length === 0) return { kind: "create" };
  if (company.length < 2) return { kind: "needs-second" };
  const visible =
    selectedId !== null &&
    shown.some((a) => a.id === selectedId) &&
    company.some((a) => a.id === selectedId);
  return { kind: "transfer", fromId: visible ? selectedId : null };
}
