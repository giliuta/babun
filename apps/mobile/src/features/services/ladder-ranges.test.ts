import assert from "node:assert/strict";
import { describe, test } from "node:test";
import { ladderRanges } from "./ladder-ranges";

describe("расшифровка ступеней", () => {
  test("ПРИМЕР ВЛАДЕЛЬЦА: 1, 3, 10", () => {
    // «Пробили 2 — считается по строке 1; пробили 5 или 8 — по строке 3;
    //  пробили 12 — по строке 10.»
    assert.equal(
      ladderRanges(["1", "3", "10"]),
      "1–2 · 3–9 · 10 и выше",
    );
  });

  test("соседние пороги печатаются одним числом, а не «3–3»", () => {
    assert.equal(ladderRanges(["1", "2", "3"]), "1 · 2 · 3 и выше");
  });

  test("одна ступень не расшифровывается", () => {
    assert.equal(ladderRanges(["1"]), null);
  });

  test("пустые и нечисловые строки не ломают расчёт", () => {
    // Только что добавленная строка стоит пустой, пока в неё не написали.
    assert.equal(ladderRanges(["1", "", "5"]), "1–4 · 5 и выше");
    assert.equal(ladderRanges(["1", "—", "0", "-3"]), null);
  });

  test("порядок ввода не важен, дубли схлопываются", () => {
    assert.equal(ladderRanges(["10", "1", "3"]), "1–2 · 3–9 · 10 и выше");
    assert.equal(ladderRanges(["1", "3", "3"]), "1–2 · 3 и выше");
  });

  test("дробные пороги не притворяются целыми", () => {
    // Количество в продукте целое, но поле принимает что угодно — расчёт не
    // должен выдавать «1–1.5» как осмысленный диапазон.
    assert.equal(ladderRanges(["1", "2.5"]), "1–1.5 · 2.5 и выше");
  });
});
