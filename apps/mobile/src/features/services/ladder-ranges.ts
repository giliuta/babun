//
// Строки прайса — ПОРОГИ: действует последняя, чей порог не выше пробитого
// количества (`resolveTier` в `services-pricing`). Пока в подписи стояло
// «от», это читалось само; владелец «от» убрал 2026-08-27, и столбец
// «1 · 3 · 10» перестал объяснять, что пятёрка считается по строке 3, а
// двенадцать — по строке 10.
//
// Возвращать «от» в каждую ячейку не надо: оно занимало место в самой узкой
// колонке и повторялось столько раз, сколько строк. Диапазоны печатаются
// ОДИН раз и целиком — и читаются как ответ, а не как приписка к числу.
//
// Живёт отдельным файлом, чтобы проверяться тестом: расчёт границ — это
// арифметика, и глазами на симуляторе её не проверить (набрать «20» в поле
// с курсором в начале строки не выходит вовсе).

/** «1–2 · 3–9 · 10 и выше». `null` — расшифровывать нечего. */
export function ladderRanges(quantities: readonly string[]): string | null {
  const nums = [
    ...new Set(
      quantities
        .map((raw) => Number(String(raw).trim().replace(",", ".")))
        .filter((n) => Number.isFinite(n) && n > 0),
    ),
  ].sort((a, b) => a - b);
  // Одна ступень — диапазон «1 и выше» не сообщает ничего, чего не видно.
  if (nums.length < 2) return null;
  return nums
    .map((from, i) => {
      const next = nums[i + 1];
      if (next === undefined) return `${from} и выше`;
      // Соседние пороги (3 и 4) дают диапазон из одного числа — печатаем его
      // одним числом, а не «3–3».
      return next - from === 1 ? `${from}` : `${from}–${next - 1}`;
    })
    .join(" · ");
}
