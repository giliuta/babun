// СЕРВЕР НЕ ОТВЕТИЛ — ИЛИ ОТКАЗАЛ? (владелец 03.10, зависший сервер)
//
// Опрос роли падал вместе с сервером, и запрос роли уходил в «ошибку», хотя
// сама роль была известна. Двадцать мест в приложении включают свои запросы
// только при «опрос роли успешен» — выключенный запрос без данных висит
// «загрузкой» вечно: «Финансы» крутились без конца, карточка клиента писала
// «Доступ не подтверждён». Поэтому НЕОТВЕТ оставляет прежнюю роль, а ОТКАЗ
// (4xx: прав нет, сессия чужая) — по-прежнему ошибка. Отзыв доступа приезжает
// ответом сервера (`null`), а не его отсутствием, — он работает как раньше.

/** Нет ответа: истекло время, нет сети (`status` 0) или упал сам сервер
 *  (5xx, в том числе 522/524 шлюза). */
export function roleLookupUnanswered(input: { status?: number | null; thrown?: boolean }): boolean {
  if (input.thrown) return true;
  const status = input.status ?? 0;
  return status === 0 || status >= 500;
}
