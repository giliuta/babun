import { View } from "react-native";
import { WEEKDAY_LABELS } from "@babun/shared/local/services";
import { LabelTag } from "@/components/ui/LabelTag";
import { useThemeColors } from "@/theme/colors";

// ЗЕРКАЛО НЕДЕЛИ — как календарь будет выглядеть с этим расписанием.
//
// Владелец 2026-08-30: «мы сразу на неделе внизу построим — грубо говоря
// зеркало: если метка стоит во вторник, внизу показывается уже метка, как
// будет выглядеть в календаре».
//
// ПОЧЕМУ ЭТО НЕ ВРЁТ ПРО БЕССРОЧНОСТЬ, А СПИСОК ДАТ ВРАЛ. Здесь неделя
// ТИПОВАЯ, без чисел: у неё нет ни первой даты, ни последней, и «докуда это
// действует» она не обещает вовсе. Список «30 авг · 31 авг · 2 сен» обещал
// ровно три дня — своим существованием, независимо от подписи.
//
// ЗЕРКАЛО, А НЕ ПОХОЖАЯ КАРТИНКА: корешок берётся из `LabelTag` — того самого
// примитива, которым метки нарисованы в шапке календаря и на карточке
// клиента. Нарисовать «в том же духе» своей вёрсткой значило бы обещать одно,
// а показать другое — и разойтись с календарём на первой же его правке.
//
// ОНО ЖЕ ЗАМЕНИЛО ПОДПИСИ НА ПЛИТКАХ. Раньше занятый день назывался именем
// хозяина мелким шрифтом под буквой дня — своя вёрстка, свой размер, обрезка
// до пяти букв. Теперь хозяин виден там, где он и будет: в неделе, целиком.
//
// БЕЗ СВОЕГО РЯДА «ПН ВТ СР». Он был — и на экране оказалось, что это вторая
// строка одних и тех же букв прямо под плитками. Колонку называет ПЛИТКА, а
// зеркало стоит в той же семиколоночной сетке ровно под ней: корешок и так
// стоит под своим днём. Красный цвет выходных ушёл вместе с рядом — плитки
// его и не носили, а два разных способа сказать «суббота» в одном блоке
// спорили бы между собой.

const ISO_DAYS = [1, 2, 3, 4, 5, 6, 7] as const;

export function WeekMirror({
  weekdays,
  color,
  name,
  takenBy,
  daysOff,
}: {
  /** ISO-номера дней, выбранных для этой метки. */
  weekdays: number[];
  color: string;
  /** Имя правимой метки. Пустое, пока его не ввели. */
  name: string;
  /** День недели → чужая метка, которая его держит. */
  takenBy: Map<number, { name: string; color: string | null }>;
  daysOff: Set<number>;
}) {
  const t = useThemeColors();
  const own = name.trim();

  return (
    <View style={{ flexDirection: "row", marginTop: 8 }}>
      {ISO_DAYS.map((day) => {
        const mine = weekdays.includes(day);
        const holder = takenBy.get(day);
        const off = daysOff.has(day);
        return (
          <View
            key={day}
            // Ряд корешков ФИКСИРОВАННОЙ ВЫСОТЫ, как в шапке календаря:
            // слот резервируется и пустым, иначе неделя прыгает по высоте
            // при каждом тапе по плитке — прямо под пальцем.
            style={{ flex: 1, alignItems: "center" }}
            accessible
            accessibilityLabel={
              off
                ? `${WEEKDAY_LABELS[day]} — выходной`
                : mine && own
                  ? `${WEEKDAY_LABELS[day]} — метка ${own}`
                  : holder
                    ? `${WEEKDAY_LABELS[day]} — метка ${holder.name}`
                    : `${WEEKDAY_LABELS[day]} — без метки`
            }
          >
            <View style={{ height: 15, justifyContent: "center" }}>
              {off ? (
                // Выходной занимает место метки первым — тем же красным и по
                // тому же правилу, что в шапке календаря: «работаем ли»
                // важнее, чем «где».
                <LabelTag color={t.danger} text="Вых" />
              ) : mine ? (
                own ? (
                  <LabelTag color={color} text={own} />
                ) : (
                  // Имени ещё нет — но место уже занято. Пустой корешок
                  // честнее подставного слова: выдумывать метке имя,
                  // которого человек не вводил, нельзя.
                  <View
                    style={{
                      width: 22,
                      height: 13,
                      borderRadius: 4,
                      backgroundColor: `${color}29`,
                      borderWidth: 1,
                      borderColor: `${color}8c`,
                    }}
                  />
                )
              ) : holder ? (
                <LabelTag color={holder.color ?? t.faint} text={holder.name} />
              ) : null}
            </View>
          </View>
        );
      })}
    </View>
  );
}
