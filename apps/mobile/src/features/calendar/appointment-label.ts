//
// Владелец 2026-09-04: «в день целый Лимассол, но последний клиент — другая
// метка… можно даже подсвечивать другим цветом, когда метка другая, ну
// окантовку какую-то». Календарь и так красит день меткой дня; выбивающаяся
// работа обязана называть себя сама, иначе бригада уедет не туда.
//
// ПРАВИЛО РОВНО ОДНО, И ОНО УЗКОЕ: сигнал даётся, только когда У ДНЯ ЕСТЬ
// метка и метка записи ДРУГАЯ. Две ступени, и обе нужны:
//
//   • у дня метки нет → своя метка записи не «другая», она просто её метка;
//     иначе вся история засветилась бы окантовкой, ведь у прошлых дней метка
//     по расписанию не считается вовсе («прошлое не переписывается
//     настройкой», `day-label.ts`);
//   • метки совпали → сообщать «эта работа там же, где весь день» значит
//     шуметь ровно на том, что и так очевидно.
//
// Цвет берётся из справочника меток команды. Метки, которой в справочнике уже
// нет, окантовка не даётся: цвет взять неоткуда, а красить наугад — врать.

/** Строка справочника меток, какая нужна этому правилу. */
export interface AppointmentLabelCity {
  name: string;
  color: string | null;
}

export interface OffDayLabel {
  name: string;
  color: string;
}

export function resolveOffDayLabel(opts: {
  /** `appointments.city` — метка САМОЙ записи. */
  city: string | null | undefined;
  /** Имя метки дня, как его считает календарь (`resolveCalendarDayLabel`). */
  dayLabelName: string | null;
  cities: readonly AppointmentLabelCity[];
  /** Чем красить метку, которой нет в справочнике. Не задан — не красить. */
  fallbackColor?: string | null;
}): OffDayLabel | null {
  const own = (opts.city ?? "").trim();
  if (!own) return null;

  const day = (opts.dayLabelName ?? "").trim();
  if (!day || day === own) return null;

  const color = opts.cities.find((c) => c.name === own)?.color ?? opts.fallbackColor;
  return color ? { name: own, color } : null;
}
