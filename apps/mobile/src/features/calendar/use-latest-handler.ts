import { useLayoutEffect, useMemo, useRef } from "react";
import { latestCaller } from "@/features/calendar/grid-memo";

/** Стабильный по ссылке обработчик события, который зовёт свежее замыкание.
 *
 *  Нужен сетке календаря: колонки и блоки мемоизированы, и обработчик,
 *  пересоздаваемый каждым рендером экрана (`openEdit`, `createAt`,
 *  `reschedule`), перерисовывал бы их все. Обычный `useCallback` с честными
 *  зависимостями тут не спасает — у этих функций зависимостей десятки, и
 *  ссылка менялась бы почти на каждый рендер.
 *
 *  КОРОБКА ОБНОВЛЯЕТСЯ В ФАЗЕ КОММИТА, А НЕ ВО ВРЕМЯ ОТРИСОВКИ. Смена
 *  календаря идёт переходом (`startTransition`), а такой рендер React вправе
 *  отбросить. Запись в ref прямо в теле компонента оставила бы в коробке
 *  замыкание НЕ показанного экрана: перенос блока на старом календаре
 *  проверял бы пересечения по записям другого. Жесты и тапы приходят после
 *  коммита, так что к их моменту коробка уже свежая.
 *
 *  Только для событий. Резолверы, которые колонка зовёт при отрисовке
 *  (`clientName`, `labelFor`), так оборачивать нельзя: memo не узнал бы, что
 *  имена или цвета поменялись. */
export function useLatestHandler<A extends unknown[], R>(
  fn: (...args: A) => R,
): (...args: A) => R {
  const box = useRef(fn);
  useLayoutEffect(() => {
    box.current = fn;
  });
  return useMemo(() => latestCaller(box), []);
}
