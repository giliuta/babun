import { useCallback } from "react";
import type { Appointment } from "@babun/shared/local/appointments";
import { useThemeColors } from "@/theme/colors";
import {
  CANCELLED_EDGE,
  edgeColor,
  fillOver,
  parseHexOk,
} from "@/components/ui/color-contrast";

// ЦВЕТА БЛОКА ЗАПИСИ НА СЕТКЕ.
//
// Блок — это ЗАЛИВКА цветом записи на 18 % и КАНТ тем же цветом по всему
// периметру (владелец 2026-09-05: «хочу полноценное покрытие всего, чтоб ярко
// выглядело — не только левая полосочка, а внутри записи всё меняется в этот
// цвет»). Левого корешка больше нет нигде в продукте.
//
// Заливка отвечает за ГРУППИРОВКУ, кант — за КАТЕГОРИЮ. Так вышло не из
// вкуса, а из измерения: при 18 % над реальной подложкой максимум попарного
// ΔE любой тройки из сорока цветов палитры — 6.7, то есть заливка различает
// оттенки слишком слабо, чтобы называть ими сущности. Кант в полную силу
// разводит те же пары на ΔE 40–110 даже при дальтонизме.
//
// СТАТУС ЗАЛИВКУ НЕ КРАСИТ И КАНТ НЕ ЗАБИРАЕТ. Раньше блок заливался статусом
// на 12 %, и весь календарь был голубым: «запланировано» — девять записей из
// десяти, то есть заливка не говорила ничего. Статус носят отдельные каналы:
// выполненная — зелёный знак в углу и заливка вполовину тише, отменённая —
// нейтральные чернила и РАЗОМКНУТЫЙ кант (зачёркивание имени остаётся, но
// живёт только там, где строка влезает), просроченная — СВОЙ ЦВЕТ и кант вдвое
// толще.
//
// ЯНТАРНЫЙ КАНТ ПРОСРОЧКИ УБРАН. Он крал единственный канал категории и ничего
// не покупал: с оранжевым «нет объекта» янтарь давал ΔE 5.4, а при
// дейтеранопии — 0.5, то есть тот же самый цвет; при протанопии оба канта
// сходятся в один #6d5f00, ΔE 0.0. Компенсировать должен был угловой знак, но
// глиф рисуется только от ширины 96pt: в колонке недели (46pt) выходил голый
// кружок, а при двух наложенных записях (21pt) не было и его. Сколько работ не
// закрыто — вопрос уровня ДНЯ, и отвечают на него лента словом «не закрыта» и
// счётчик в клетке Месяца.

// ЗАКОН ОТМЕНЫ: СПЛОШНОЙ КОНТУР — РАБОТА БУДЕТ, РАЗОМКНУТЫЙ — НЕ БУДЕТ.
//
// Сами значения живут в `components/ui/color-contrast` рядом с `edgeColor`:
// ими красят сетка, лента И образец в настройке, а слой `components/ui` не
// имеет права тянуть из `features`. Здесь — причины, по которым они такие.
//
// ПОЧЕМУ НЕ ОТТЕНОК. Кант отменённой #5e6169 и кант серой ситуации «нет
// клиента» edgeColor("#8E8E93") = #66666a дают друг к другу 1.084 : 1 —
// разницы нет ни для кого, не только для дальтоника; Графитовый даёт 1.83 : 1,
// тоже мало. Оба цвета лежат в палитре, и владелец вправе назначить их любой
// ситуации, команде или метке: решение, опирающееся на оттенок, чинится и
// ломается обратно одной настройкой.
//
// ПОЧЕМУ НЕ «СДЕЛАТЬ ОТМЕНЁННУЮ ПОЛОЙ». Её заливка (чернила 7.84 % над
// подложкой сетки) — #c0bfc7, заливка серой записи (18 %) — #c3c2c9, ΔE 1.2.
// Убрать заливку значит поменять почти-серый на серый фон (1.13 : 1). Канал
// заливки для этой пары мёртв.
//
// ИНВАРИАНТ RN, КОТОРЫЙ СТИРАЕТ КАНТ МОЛЧА: у блока с пунктиром `borderWidth`
// и `borderColor` обязаны быть ЕДИНЫМИ по всем сторонам — при разных цветах
// сторон кант исчезает ЦЕЛИКОМ, без отката на сплошной. Шаг штриха зашит как
// 3×borderWidth и не настраивается, поэтому у отменённой толщина обязана
// остаться 1: при 2 период 12pt разваливается на узком блоке. Толщина 2 у неё
// недостижима и по смыслу — просрочка требует статуса «запланирована».
export { CANCELLED_BORDER, CANCELLED_EDGE } from "@/components/ui/color-contrast";

export type BlockColors = {
  /** Цвет записи, всегда шестизначный hex. */
  hue: string;
  /** Заливка карточки, КАК ОНА ВЫГЛЯДИТ НА СЕТКЕ, — непрозрачный композит
   *  цвета на 18 % поверх худшей подложки.
   *
   *  НЕПРОЗРАЧНЫЙ, И ЭТО ВАЖНО. Раньше здесь лежала строка `${hue}2e` — цвет
   *  С АЛЬФОЙ, — и её передавали в `deepen` фоном для точки чужой метки.
   *  Измеритель альфу отбрасывает (так и написано в `parseHex`: контраст
   *  меряется по КОМПОЗИТУ), поэтому фоном считался ПОЛНЫЙ цвет записи вместо
   *  его восемнадцати процентов: зелёная метка на кобальтовой записи
   *  затемнялась до #11401c — почти чёрного — при контрасте 5.98 : 1 вместо
   *  нужных трёх. Точка существует затем, чтобы цвет метки был УЗНАВАЕМ, и
   *  теряла ровно это. Рисовать блок этим значением нельзя и не нужно:
   *  карточку красит `fillRgba` в анимированном стиле. */
  fill: string;
  /** Кант по периметру: тот же цвет, затемнённый под порог 3 : 1. */
  edge: string;
};

const cache = new Map<string, BlockColors>();

/** Цвета блока для одного цвета записи. Чистая, поэтому её видит тест: гейт
 *  «фон для затемнения непрозрачен» обязан меряться о то же самое значение,
 *  которым красит календарь. */
export function blockColorsFor(hue: string): BlockColors {
  const hit = cache.get(hue);
  if (hit) return hit;
  // ОДИН И ТОТ ЖЕ ОБЪЕКТ НА ОДИН ЦВЕТ: свежий литерал на каждый рендер ломал
  // бы `React.memo` у полутора сотен блоков смонтированной недели.
  const out: BlockColors = { hue, fill: fillOver(hue), edge: edgeColor(hue) };
  cache.set(hue, out);
  return out;
}

/** Возвращает распознаватель цвета блока. `teamColorFor` приходит с экрана
 *  календаря и уже содержит полное правило записи (`record-color`). */
export function useBlockColors(
  teamColorFor?: (a: Appointment) => string | null,
) {
  const t = useThemeColors();
  return useCallback(
    (apt: Appointment): BlockColors => {
      const raw =
        (apt.color_override as string | null | undefined) ||
        (teamColorFor ? teamColorFor(apt) : null) ||
        t.accent;
      // ГЕЙТ «ЦВЕТ ВСЕГДА HEX». Раньше запасным значением служил цвет
      // СТАТУСА, а он у отменённой брался из токена `t.faint`, то есть
      // `rgba(11,18,32,0.64)`. Из него собиралась строка заливки
      // `rgba(...)2e` — не цвет вовсе, и блок оставался прозрачным. Путь
      // живой: личное событие без команды видно в любом календаре.
      return blockColorsFor(parseHexOk(raw) ? raw : t.accent);
    },
    [t.accent, teamColorFor],
  );
}

/** Кант блока по статусу. Отдельной функцией, потому что кант — единственный
 *  канал КАТЕГОРИИ, и право забрать его есть ровно у одного состояния: у
 *  отменённой, которой никуда не ехать. */
export function blockEdge(
  colors: BlockColors,
  status: Appointment["status"],
): string {
  return status === "cancelled" ? CANCELLED_EDGE : colors.edge;
}

/** Заливка блока поверх названной подложки — для измерений и тестов. */
export { fillOver };
