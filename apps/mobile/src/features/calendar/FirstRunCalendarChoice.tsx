import { View } from "react-native";
import { GradientButton } from "@/components/ui/GradientButton";
import { useThemeColors } from "@/theme/colors";

// Показывается вкладкой календаря, когда у тенанта ещё нет ни одного
// командного календаря. Одна кнопка заводит первый.
//
// ЭКРАН — ТОЛЬКО КНОПКА «Создать календарь»: без плитки со значком, заголовка и
// абзаца-объяснения. Почему:
//   1. АБЗАЦ ОБЪЯСНЯЛ БЫ СЛОВО, КОТОРОЕ НЕ ТРЕБУЕТ ОБЪЯСНЕНИЯ. «Календарь —
//      это расписание» читает человек, который управляет двумя бригадами и
//      уже нажал вкладку «Календарь». Закон (§5): назвать контрол так, чтобы
//      объяснять было нечего. Кнопка «Создать календарь» называет.
//   2. ЗНАЧОК КАЛЕНДАРЯ НА ВКЛАДКЕ «КАЛЕНДАРЬ» повторял бы то, что уже сказано
//      таб-баром, заголовком и самой кнопкой, — четвёртый раз одно слово.
//   3. ЗАГОЛОВОК «Здесь будет ваш календарь» — пятый. Пустой экран не нужно
//      подписывать «здесь пусто».
//
// Разъяснительный тон — наследие веб-версии: на большом экране абзац стоил
// ничего, на телефоне он занимает треть высоты и стоит между человеком и
// единственным действием.
export function FirstRunCalendarChoice({
  onCreate,
  creating,
}: {
  onCreate: () => void;
  creating?: boolean;
}) {
  const t = useThemeColors();
  return (
    <View
      style={{
        flex: 1,
        backgroundColor: t.canvas,
        // Главное действие экрана живёт ВНИЗУ, в зоне большого пальца.
        // По центру кнопка стоит там, куда палец не
        // дотягивается на ходу, — а этим приложением пользуются стоя у
        // сплит-системы, одной рукой.
        justifyContent: "flex-end",
        paddingHorizontal: 16,
        paddingBottom: 16,
      }}
    >
      <GradientButton
        label="Создать календарь"
        onPress={onCreate}
        loading={creating}
      />
    </View>
  );
}
