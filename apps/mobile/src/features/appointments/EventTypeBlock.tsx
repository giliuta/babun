import { Tag } from "lucide-react-native";
import type { PersonalEventType } from "@babun/shared/local/personal-event-types";
import { ReferenceBlock } from "@/components/ui/ReferenceBlock";
import { eventTypeIcon } from "@/features/calendar/event-type-icons";

// ТИП СОБЫТИЯ — ТОТ ЖЕ БЛОК, ЧТО КАТЕГОРИЯ ОПЕРАЦИИ (владелец 2026-09-10:
// «этот блок удаляем и сделай его точно таким же, как в категории в финансах…
// тип события выбирается точно так же, как категория, вся архитектура как у
// категории; мне кажется, тип события будет гораздо лучше выглядеть под
// категорию»).
//
// ЧТО УБРАНО И ПОЧЕМУ. Здесь стояла горизонтальная ЛЕНТА ПЛИТОК: кружок 40pt,
// подпись 11pt в две строки, выбор одним касанием, повторный тап снимал тип,
// а дверь в справочник — значок ползунков в шапке блока. Работало, но было
// ВТОРЫМ диалектом выбора: в продукте предмет выбирают блоком со шапкой и
// шторкой (клиент, объект, услуга, категория), а тут — лентой, которую надо
// листать вбок, со своим способом снять выбор и своей дверью в справочник.
// Теперь всё то же, что у категории: строка-дверь «Выбрать тип события» →
// каноническая шторка `PickerSheet` со значком и цветом каждой строки,
// длительность типа — тихой подписью, СНЯТИЕ — повторным тапом по выбранной
// строке (владелец 2026-09-10: «убери кнопку „без типа“, и я могу тапнуть ещё
// раз на тот тип, который выбрал, и он тогда отменяется»), дверь в справочник
// — значок настроек в шапке ШТОРКИ (там он не уезжает за край вместе с лентой
// — прежняя причина держать его в шапке блока исчезла вместе с лентой).
//
// Длительность и цвет тип по-прежнему ДАЁТ: цвет события — цвет типа, а
// длительность — стандарт, который выбранное руками время не перебивает. Это
// живёт в форме (`applyEventType`), а не в блоке.

export function EventTypeBlock({
  type,
  onPress,
}: {
  /** Выбранный тип; `null` — событие без типа (оно называется «Событие»). */
  type: PersonalEventType | null | undefined;
  onPress: () => void;
}) {
  return (
    <ReferenceBlock
      title="Тип события"
      emptyIcon={Tag}
      emptyLabel="Выбрать тип события"
      emptyHint="Открывает список типов событий"
      value={
        type
          ? {
              name: type.label,
              color: type.color,
              Icon: eventTypeIcon(type.icon),
            }
          : null
      }
      onPress={onPress}
    />
  );
}
