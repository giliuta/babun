import { Tag } from "lucide-react-native";
import type { PersonalEventType } from "@babun/shared/local/personal-event-types";
import { ReferenceBlock } from "@/components/ui/ReferenceBlock";
import { eventTypeIcon } from "@/features/reference/event-type-icons";

// ТИП СОБЫТИЯ — ТОТ ЖЕ БЛОК, ЧТО КАТЕГОРИЯ ОПЕРАЦИИ: вся архитектура как у
// категории в финансах.
//
// В продукте предмет выбирают блоком со шапкой и шторкой (клиент, объект,
// услуга, категория), поэтому горизонтальная ЛЕНТА ПЛИТОК (кружок 40pt,
// подпись 11pt в две строки, выбор одним касанием, значок ползунков в шапке
// блока) стала бы ВТОРЫМ диалектом выбора: её надо листать вбок, у неё свой
// способ снять выбор и своя дверь в справочник. Здесь всё то же, что у
// категории: строка-дверь «Выбрать тип события» → каноническая шторка
// `PickerSheet` со значком и цветом каждой строки, длительность типа — тихой
// подписью, СНЯТИЕ — повторным тапом по выбранной строке (кнопки «без типа»
// нет), дверь в справочник — значок настроек в шапке ШТОРКИ (там он не уезжает
// за край вместе с лентой).
//
// Длительность и цвет тип по-прежнему ДАЁТ: цвет события — цвет типа, а
// длительность — стандарт, который выбранное руками время не перебивает. Это
// живёт в форме (`applyEventType`), а не в блоке.

export function EventTypeBlock({
  type,
  title,
  titleColor,
  onPress,
}: {
  /** Выбранный тип; `null` — событие без типа (оно называется «Событие»). */
  type: PersonalEventType | null | undefined;
  /** НАЗВАНИЕ СОБЫТИЯ БЕЗ ТИПА. У старых событий имя
   *  вписано словом («Встреча», «Перерыв»), а тип с таким именем не заведён
   *  или стёрт. Сетка подписывает блок этим именем, сохранение его бережёт, а
   *  страница показывала пустую дверь «Выбрать тип события» — будто события
   *  никак не зовут. Теперь в блоке стоит его имя; выбор типа заменит его. */
  title?: string;
  titleColor?: string | null;
  onPress: () => void;
}) {
  const freeTitle = title?.trim();
  return (
    <ReferenceBlock
      title="Тип события"
      emptyIcon={Tag}
      emptyLabel="Выбрать тип события"
      emptyHint="Открывает список типов событий"
      value={
        type
          ? {
              name: type.label,
              color: type.color,
              Icon: eventTypeIcon(type.icon),
            }
          : freeTitle
            ? { name: freeTitle, color: titleColor ?? null, Icon: Tag }
            : null
      }
      onPress={onPress}
    />
  );
}
