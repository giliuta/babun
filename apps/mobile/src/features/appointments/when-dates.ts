const MONTHS_GEN = [
  "января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря",
];

// ДВА ГОДА В ОБЕ СТОРОНЫ от выбранного дня. Полгода не хватало: визит на
// сезон вперёд (чистка кондиционеров весной следующего года) не ставился
// вовсе, а прошлогоднюю операцию нельзя было вписать задним числом. Страницы
// полосы ленивые (`getItemLayout`), длина списка ничего не стоит.
export const WHEN_WEEKS_BACK = 104;
export const WHEN_WEEKS_FWD = 104;

/** «5 марта», в другом году — «5 марта 2027»: заголовок листа называет день,
 *  и «5 марта» через год читалось бы как ближайшее. */
export function formatDateRu(dateKey: string, today: Date = new Date()): string {
  const [y, m, d] = dateKey.split("-").map(Number);
  const day = `${d} ${MONTHS_GEN[m - 1]}`;
  return y === today.getFullYear() ? day : `${day} ${y}`;
}
