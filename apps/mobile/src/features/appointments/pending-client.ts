// Владелец 2026-08-31: «нажимаю создать клиента, добавляю имя, номер
// телефона, нажимаю „Готово" — и оно остаётся на странице клиента. А должно
// сразу переходить в саму запись и подтягивать это всё, потому что я ж делаю
// в первую очередь ЗАПИСЬ».
//
// До этого форма записи уходила в тупик: из неё открывалась карточка нового
// клиента, после сохранения `router.replace` уводил на карточку СОЗДАННОГО, и
// путь вперёд кончался — оставалось только «назад». Человек начинал запись, а
// получал клиента.
//
// ПОЧЕМУ НЕ ХВАТИЛО ПРОСТОГО `router.back()`, хотя сперва казалось, что хватит.
// Проверено на симуляторе: `/clients/new` живёт ВНУТРИ вкладки «Клиенты», а
// форма записи — маршрут корневого стека НАД табами (так и написано в
// `app/book/_layout.tsx`). Переход к созданию клиента уводит из формы совсем,
// и возвращаться из неё уже некуда: «назад» приводит на календарь.
//
// Поэтому ящик несёт не только клиента, но и САМ СЛОТ — дату, время и
// команду, которые человек выбрал ДО того, как пошёл заводить клиента. После
// сохранения форма открывается заново уже с ними и с новым клиентом, и для
// человека это выглядит как продолжение, а не как «начни сначала».
//
// Ящик живёт в памяти модуля и опустошается ЧТЕНИЕМ: слот, забранный один
// раз, не должен подставиться во вторую запись через час.

/** Слот, ради которого человек пошёл заводить клиента. */
export interface BookingReturn {
  date?: string;
  timeStart?: string;
  teamId?: string | null;
}

let stash: BookingReturn | null = null;

/** Форма записи: «ушёл за клиентом, вот куда меня вернуть». */
export function stashBookingReturn(value: BookingReturn): void {
  stash = value;
}

/** Карточка клиента: ждёт ли запись этого клиента обратно. Не опустошает —
 *  решение «куда идти» принимается до самого перехода. */
export function bookingIsWaitingForClient(): boolean {
  return stash !== null;
}

/** Карточка клиента: забрать слот и опустошить ящик. */
export function takeBookingReturn(): BookingReturn | null {
  const value = stash;
  stash = null;
  return value;
}

/** Человек передумал заводить клиента и ушёл — ящик надо опустошить, иначе
 *  следующее создание клиента (уже из справочника) уедет в запись. */
export function clearBookingReturn(): void {
  stash = null;
}
