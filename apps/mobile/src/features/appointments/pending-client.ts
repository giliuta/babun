// КАК ЭТО БЫЛО УСТРОЕНО ДО 2026-09-03 И ПОЧЕМУ ПЕРЕДЕЛАНО. Форма записи
// уходила на `/clients/new` — маршрут ВНУТРИ вкладки «Клиенты», — а сама
// она живёт в корневом стеке НАД табами. Такой переход клал поверх записи
// целую вторую копию табов: «назад» из карточки приводил на календарь этой
// копии, а запись оставалась висеть под ним с набранным и без дороги к ней
// (проверено на симуляторе: «Отмена» → «<» — и человек на календаре, запись
// потеряна без вопроса). Чтобы после «Готово» запись всё же открылась, здесь
// лежал ящик со слотом, и форма открывалась ЗАНОВО — уже без услуг, заметки
// и предоплаты, набранных до похода за клиентом.
//
// ТЕПЕРЬ карточка нового клиента открывается ПОВЕРХ записи — маршрутом
// `/book/client` в том же корневом стеке. Запись остаётся смонтированной со
// всем набранным, «назад» возвращает ровно в неё, а «Готово» отдаёт сюда id
// созданного клиента и делает `router.back()`. Форма записи забирает id,
// получив фокус, и выбирает клиента тем же `pickClient`, что и тап по
// списку, — со всеми его следствиями (объект, мастер, цепочка услуг).
//
// Ящик живёт в памяти модуля и опустошается ЧТЕНИЕМ, а через минуту
// протухает сам: id, доставленный в форму, которой уже нет, не должен
// подставиться в следующую запись через час.

interface DeliveredClient {
  clientId: string;
  at: number;
}

/** Сколько доставка ждёт форму. Возврат «назад» занимает доли секунды;
 *  минута — запас с большим избытком. */
const DELIVERY_TTL_MS = 60_000;

let delivered: DeliveredClient | null = null;

/** Карточка нового клиента: «клиент создан, вот его id — заберите». */
export function deliverCreatedClient(clientId: string): void {
  delivered = { clientId, at: Date.now() };
}

/** Форма записи: забрать доставленного клиента и опустошить ящик. */
export function takeCreatedClient(): string | null {
  const value = delivered;
  delivered = null;
  if (!value || Date.now() - value.at > DELIVERY_TTL_MS) return null;
  return value.clientId;
}
