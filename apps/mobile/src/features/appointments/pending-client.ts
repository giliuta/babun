import type { Client } from "@babun/shared/local/clients";

// КЛИЕНТ, СОЗДАННЫЙ РАДИ ЗАПИСИ, — ВОЗВРАЩАЕТСЯ В ЗАПИСЬ.
//
// После «Готово» на карточке нового клиента человек должен оказаться в самой
// записи с подтянутым клиентом, а не остаться на странице клиента: запись — то,
// что он делает в первую очередь.
//
// Карточка нового клиента открывается ПОВЕРХ записи — маршрутом `/book/client`
// в том же корневом стеке. Если бы форма уходила на `/clients/new` (маршрут
// ВНУТРИ вкладки «Клиенты», а запись живёт в корневом стеке НАД табами), такой
// переход клал бы поверх записи целую вторую копию табов: «назад» приводил бы
// на календарь этой копии, а запись оставалась бы висеть под ним с набранным и
// без дороги к ней. Запись остаётся смонтированной со всем набранным, «назад»
// возвращает ровно в неё, а «Готово» отдаёт сюда id созданного клиента и делает
// `router.back()`. Форма записи забирает id, получив фокус, и выбирает клиента
// тем же `pickClient`, что и тап по списку, — со всеми его следствиями (объект,
// мастер, цепочка услуг).
//
// Ящик живёт в памяти модуля и опустошается ЧТЕНИЕМ, а через минуту
// протухает сам: id, доставленный в форму, которой уже нет, не должен
// подставиться в следующую запись через час.

interface DeliveredClient {
  clientId: string;
  /** Строка клиента, если форма может её не знать: партнёр выбрал по «Номер
   *  уже есть» клиента другой команды — в его списке такого клиента нет,
   *  пока запись не сохранена. */
  row: Client | null;
  at: number;
}

/** Сколько доставка ждёт форму. Возврат «назад» занимает доли секунды;
 *  минута — запас с большим избытком. */
const DELIVERY_TTL_MS = 60_000;

let delivered: DeliveredClient | null = null;

/** Карточка нового клиента: «клиент создан, вот его id — заберите». */
export function deliverCreatedClient(clientId: string, row: Client | null = null): void {
  delivered = { clientId, row, at: Date.now() };
}

/** Забрать доставленного клиента вместе со строкой и опустошить ящик. */
export function takeDeliveredClient(): { clientId: string; row: Client | null } | null {
  const value = delivered;
  delivered = null;
  if (!value || Date.now() - value.at > DELIVERY_TTL_MS) return null;
  return { clientId: value.clientId, row: value.row };
}

/** Форма записи: забрать доставленного клиента и опустошить ящик. */
export function takeCreatedClient(): string | null {
  return takeDeliveredClient()?.clientId ?? null;
}
