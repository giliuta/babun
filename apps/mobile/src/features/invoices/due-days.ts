// СРОК ОПЛАТЫ — КЛАВИШАМИ (владелец 03.10: страница «Инвойсы» в новом виде;
// его же закон «ответ виден, один тап»). Число в поле прятало ответ за
// клавиатурой и требовало подписи «дней после выставления…», а такие подписи
// под строками он снимает везде.
//
// 0 — оплата по факту: срок равен дню выставления.
export const DUE_DAY_PRESETS: readonly number[] = [0, 7, 14, 30];

/** Клавиши срока. Срок, выставленный раньше вне набора (10 дней), остаётся
 *  своей клавишей на своём месте: иначе ни одна клавиша не горела бы и
 *  настройка выглядела бы сброшенной. */
export function dueDayOptions(current: number): { value: string; label: string }[] {
  const days = DUE_DAY_PRESETS.includes(current)
    ? [...DUE_DAY_PRESETS]
    : [...DUE_DAY_PRESETS, current].sort((a, b) => a - b);
  return days.map((d) => ({ value: String(d), label: d === 0 ? "По факту" : String(d) }));
}
