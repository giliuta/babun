// ПОИСК «СОДЕРЖИТ» ДЛЯ ILIKE — СИМВОЛЫ ШАБЛОНА ЭКРАНИРУЮТСЯ.
//
// `%` и `_` в LIKE — подстановки: запрос «50%» искал «50 и что угодно
// дальше», а «_» совпадал с любой буквой (аудит 2026-10-03: поиск по
// заметкам операций находил всё подряд). Обратная косая — экранирующий
// символ Postgres по умолчанию, её саму тоже экранируем.
export function containsPattern(query: string): string {
  return `%${query.replace(/[\\%_]/g, (ch) => `\\${ch}`)}%`;
}
