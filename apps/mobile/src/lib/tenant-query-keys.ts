/** Ключ запроса НАЗЫВАЕТ какую-то из компаний человека — значит принадлежит ей
 *  и чужого не покажет: под другой компанией у запроса другой ключ.
 *
 *  Сверять надо со ВСЕМИ компаниями, а не только с той, куда идём. Версия,
 *  берёгшая одну лишь компанию назначения, ровно этим стирала кэш покидаемой:
 *  круг «AirFix → Giliuta → AirFix» оставался холодным на обратном пути, и
 *  человек снова видел скелет вместо записей. */
export function keyNamesKnownTenant(
  key: readonly unknown[],
  tenantIds: readonly string[],
): boolean {
  return key.some(
    (part) => typeof part === "string" && tenantIds.includes(part),
  );
}
