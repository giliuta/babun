// КАКОЙ ЗАПРОС ПЕРЕЖИВАЕТ ПЕРЕХОД В ДРУГУЮ КОМПАНИЮ.
//
// Лист без зависимостей — намеренно. Живя внутри `auth-clear.ts`, это правило
// было непроверяемым: тот файл тянет supabase, уведомления и react-query, и
// тест на нём не поднимается вовсе (react-native не разбирается раннером).
// Поэтому единственное, чем его можно было «проверить», — чтение глазами, а
// именно на нём правило уже один раз и сломалось.

/** Ключ запроса НАЗЫВАЕТ какую-то из компаний человека — значит принадлежит ей
 *  и чужого не покажет: под другой компанией у запроса другой ключ.
 *
 *  Сверять надо со ВСЕМИ компаниями, а не только с той, куда идём. Версия,
 *  берёгшая одну лишь компанию назначения, ровно этим стирала кэш покидаемой:
 *  круг «AirFix → Giliuta → AirFix» оставался холодным на обратном пути, и
 *  человек снова видел скелет вместо записей. */
export function keyNamesKnownTenant(
  key: readonly unknown[],
  tenantIds: readonly string[],
): boolean {
  return key.some(
    (part) => typeof part === "string" && tenantIds.includes(part),
  );
}

/** Запросы, которые принадлежат ЧЕЛОВЕКУ, а не компании, и потому переход
 *  переживают, хотя компанию в ключе не называют.
 *
 *  Первый и главный — лента календарей: она ОДНА на все компании и она же
 *  единственный переключатель. Снося её на каждом переходе, чистка оставляла
 *  ряд чипов пустым до ответа сети, а без сети — вернуться в свою компанию было
 *  нечем. Это нашёл аудит 2026-09-13, и это была моя же ошибка: предикат по
 *  «называет компанию» честно не находил компании в ключе `["my-calendars",
 *  userId]` и сносил его. */
const PERSON_SCOPED_QUERY_HEADS: readonly string[] = ["my-calendars"];

/** Переживает ли запрос переход в другую компанию. */
export function querySurvivesSwitch(
  key: readonly unknown[],
  tenantIds: readonly string[],
): boolean {
  return (
    keyNamesKnownTenant(key, tenantIds) ||
    (typeof key[0] === "string" && PERSON_SCOPED_QUERY_HEADS.includes(key[0]))
  );
}
