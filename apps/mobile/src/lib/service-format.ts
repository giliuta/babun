/** Длительность по-человечески: «45 мин», «1 ч», «1 ч 30 мин».
 *
 *  Услуга печатает длительность на четырёх поверхностях (справочник, пикер
 *  услуг, сводка записи, страница записи), и если бы каждая считала её сама,
 *  справочник печатал бы сырые «90 мин», а выбор услуги рядом — «1 ч 30 мин».
 *  Одна услуга звучала бы двумя способами в двух тапах друг от друга. */
export function durationLabel(totalMinutes: number): string {
  const minutes = Math.max(0, Math.round(totalMinutes));
  const hours = Math.floor(minutes / 60);
  const rest = minutes % 60;
  if (hours === 0) return `${rest} мин`;
  return rest === 0 ? `${hours} ч` : `${hours} ч ${rest} мин`;
}

/** Длительность для УЗКОЙ ячейки: «1 ч 30», «1 ч», «45 мин».
 *
 *  Колонка «Время» лестницы цен — 94 pt, внутри 74: полное «1 ч 30 мин» туда
 *  не входит и обрезалось многоточием («1 ч 30 …») — у ступени нельзя было
 *  прочитать её же время. Слово «мин» после часов уходит: «1 ч 30» читается
 *  однозначно, а без часов минуты остаются со словом — голое «45» было бы
 *  числом без единицы. */
export function durationShort(totalMinutes: number): string {
  const minutes = Math.max(0, Math.round(totalMinutes));
  const hours = Math.floor(minutes / 60);
  const rest = minutes % 60;
  if (hours === 0) return `${rest} мин`;
  return rest === 0 ? `${hours} ч` : `${hours} ч ${rest}`;
}

/** Потолок барабана: часы кольцом 0–23, минуты по 5. Больше суток услуга не
 *  длится, а ветка «конец суток» у примитива при 23 не срабатывает никогда. */
const MAX_DURATION = 23 * 60 + 55;

/** Минуты — к шагу барабана. Барабан крутит пятиминутками, и значение,
 *  пришедшее из базы не кратным (наследие ручного ввода), обязано лечь на
 *  ближайшую метку: иначе оно молча округлится при первом же повороте. */
export function roundToStep(minutes: number): number {
  return Math.min(MAX_DURATION, Math.max(0, Math.round(minutes / 5) * 5));
}
