import type { QueryClient } from "@tanstack/react-query";

// ОПРОС РОЛИ ПЕРЕВЗВОДИТСЯ НА КАЖДОЙ СМЕНЕ ФАЗЫ ДООБНОВЛЕНИЯ.
//
// Интервал опроса — функция (`rolePollInterval`): пока тихая очередь читает
// сеть, опроса нет. Но react-query пересчитывает такую функцию не на тике, а
// только когда меняются опции наблюдателя (`setOptions`, и то если значение
// другое) или сам запрос (`onQueryUpdate`). Очередь стартует через 2 с после
// перехода — ни опции, ни запрос роли в этот момент не меняются, и взведённые
// 60 с тикали бы сквозь всю очередь.
//
// Поэтому на каждой смене фазы наблюдателям роли отдаются их же опции:
//   • очередь пошла — значение стало `false`, таймер снят;
//   • очередь стихла или переход сорвался — снова 60 с, таймер взведён;
//   • фаза только запланирована — значение прежнее, таймер не сбрасывается.
// Запроса это не вызывает: те же опции и тот же запрос не проходят
// `shouldFetchOptionally`, а равные опции не шлют и уведомления.
//
// Лист без react-native: поведение проверяет тест с настоящим `QueryClient`.

/** Отдать наблюдателям роли их же опции — react-query пересчитает интервал. */
export function rearmRolePollers(client: QueryClient, head: string): void {
  for (const query of client.getQueryCache().findAll({ queryKey: [head] })) {
    for (const observer of query.observers) observer.setOptions(observer.options);
  }
}
