import type { QueryClient } from "@tanstack/react-query";
import {
  PERSON_SCOPED_QUERY_HEADS,
  querySurvivesSwitch,
} from "./tenant-query-keys";

// ЧТО ПЕРЕХОД ДЕЛАЕТ С КЭШЕМ ЗАПРОСОВ — ЛИСТОМ, ЧТОБЫ ТЕСТ ЗВАЛ НАСТОЯЩЕЕ.
//
// Жило внутри `auth-clear.ts`, а тот тянет supabase, уведомления и MMKV —
// тест повторял строки «дословно» и сторожил копию, а не код. Копия не падает,
// когда ломают оригинал.

/** Чистка кэша запросов при переходе между компаниями человека.
 *
 *  1. Запрос, ключ которого не называет ни одну из компаний человека и не
 *     принадлежит самому человеку, сносится: он мог бы показать карточку
 *     клиента прежней фирмы (`["client", id]`).
 *  2. Запросы компаний остаются как есть — С ИХ СВЕЖЕСТЬЮ. Пометки «протух»
 *     больше нет: она делала каждый смонтированный экран залпом в сеть, а
 *     бесплатный план держал этот залп в очереди по 3–5 с на запрос. Когда
 *     что перечитать, решает возраст данных (`switch-revalidate-plan.ts`).
 *  3. Лента календарей перечитывается сразу — разбор ниже. */
export function sweepQueryCacheOnSwitch(
  qc: QueryClient,
  knownTenantIds: readonly string[],
): void {
  qc.removeQueries({
    predicate: (q) => !querySurvivesSwitch(q.queryKey, knownTenantIds),
  });

  // ЗАПРОСЫ ЧЕЛОВЕКА ПЕРЕЗАПРАШИВАЮТСЯ СРАЗУ, И ЭТО ИСКЛЮЧЕНИЕ ИЗ ПРАВИЛА ВЫШЕ.
  //
  // Лента календарей одна на все компании, но сервер помечает в ней
  // активную (`is_active = t.tenant_id = current_tenant_id()`), и после
  // перехода эта пометка стоит на ПРЕЖНЕЙ компании, пока список не
  // перезапрошен. Пока я сносил этот запрос, он перезапрашивался сам; когда
  // стал беречь (офлайн без него не вернуться), наружу вылезло: в ленте свои
  // календари новой компании дважды — заливкой и, из старого списка,
  // обводкой как чужие, — а календари покидаемой пропали.
  //
  // Флаг `isActive` в кэшированной ленте руками НЕ переставляется: ровно так
  // и получались двойные чипы. Лента перечитывается целиком.
  //
  // Компания в заголовке уже новая, ответ приедет за одну поездку. Ключ
  // компанию не называет, поэтому «ждать своего возраста» ему не подходит:
  // наблюдатель у него один и тот же по обе стороны перехода.
  for (const head of PERSON_SCOPED_QUERY_HEADS) {
    void qc.invalidateQueries({
      queryKey: [head],
      refetchType: "active",
    });
  }
}

/** Компании, чьи запросы переживают переход.
 *
 *  Из ленты календарей в кэше, а не из токена: `getSession()` ради списка
 *  стоил асинхронного шага на пути тапа, а после часа офлайна отвечал пустой
 *  сессией. Лента уже лежит в памяти — по ней нарисован сам чип, в который
 *  тапнули. Её может не быть (холодный старт без сети) — тогда достаточно двух
 *  компаний, между которыми идёт переход: лишнего список не сохранит, ключ без
 *  компании сносится. */
export function knownTenantsForSwitch(input: {
  target: string;
  leaving: string | null;
  calendars: readonly { tenantId: string }[] | undefined;
}): string[] {
  const known = new Set<string>([input.target]);
  if (input.leaving) known.add(input.leaving);
  for (const calendar of input.calendars ?? []) {
    if (typeof calendar.tenantId === "string" && calendar.tenantId) {
      known.add(calendar.tenantId);
    }
  }
  return [...known];
}
