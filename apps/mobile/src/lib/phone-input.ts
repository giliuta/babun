/** ЧИСТКА ВВОДА НОМЕРА. keyboardType="phone-pad" убирает буквы с ЭКРАННОЙ
 *  клавиатуры, но не из ПОЛЯ: диктовка, вставка из буфера, автозамена и
 *  внешняя клавиатура несут буквы напрямую (владелец 2026-07-26: «в номер
 *  телефона могу писать буквы, а так не должно быть»). Оставляем ровно то,
 *  из чего состоит номер: цифры, ведущий «+», разделители набора.
 *
 *  Живёт в lib, а не в фиче клиентов: телефонные поля есть и у карточки
 *  клиента, и у примитивов строк (components/ui/card-rows) — ui-слой не
 *  должен тянуть импорты из фич. */
export function sanitizePhoneInput(raw: string): string {
  // Пробел разрешён (им разделяют группы цифр), а перевод строки и таб —
  // нет: вставка «Имя ⏎ +357 99 …» из мессенджера иначе оставляла в поле
  // только «+», а номер терялся (AsYouType обрывается на переводе строки).
  const s = (raw ?? "").replace(/[\n\r\t]+/g, " ").replace(/[^\d+() -]/g, "");
  // «+» осмыслен только первым символом — внутри номера это мусор.
  const plus = s.trimStart().startsWith("+");
  const body = s.replace(/\+/g, "");
  return plus ? `+${body}` : body;
}
