// ЧТО ЧИСТКА ДЕЛАЕТ С УВЕДОМЛЕНИЯМИ — РЕШЕНИЕ ОДНО, И ОНО ПРОВЕРЯЕМОЕ.
//
// Лист без зависимостей намеренно: внутри `auth-clear.ts` это правило нельзя
// проверить тестом вовсе (файл тянет supabase, уведомления и react-query, и
// раннер на нём не поднимается). Единственной «проверкой» осталось бы чтение
// глазами — а именно на таких проверках мы сегодня уже дважды обожглись.

export type WipeNotificationsPlan = "clear" | "none";

/** Решение: трогать ли нативные уведомления при этой чистке.
 *
 *  ВЫХОД ИЗ АККАУНТА / СМЕНА ЧЕЛОВЕКА → `clear`. Это единственное, ради чего
 *  правило писалось: на устройстве может оказаться ДРУГОЙ человек, и имена
 *  чужих клиентов не имеют права остаться на локскрине. Гасить надо ДО того,
 *  как уйдут кэши, — иначе между двумя шагами остаётся окно.
 *
 *  ПЕРЕХОД В ДРУГУЮ КОМПАНИЮ → `none`, и это снятие прежнего требования.
 *  Человек ТОТ ЖЕ и состоит в ОБЕИХ компаниях: напоминание про клиента AirFix,
 *  пришедшее пока он смотрит Giliuta, — его собственное напоминание, а не
 *  утечка. Приватности здесь не было никогда, а цена была:
 *
 *  • ВРЕМЯ. `suspendAllBabunNotifications` — три нативных вызова, и идут они
 *    через общую очередь планировщика, вставая за любой уже идущей работой с
 *    напоминаниями (а она идёт как раз после загрузки записей). Замер на
 *    симуляторе: 272 мс из 981 мс всего перехода.
 *  • НАПОМИНАНИЯ. Та же функция снимает с расписания нативные уведомления
 *    ОБЕИХ компаний, а восстанавливаются они только у той, чьи данные потом
 *    загрузились. Человек уходил в личный календарь — и напоминания по рабочим
 *    заявкам физически переставали срабатывать до возвращения. Пока переход
 *    сносил и кэш, это терялось на общем фоне; теперь, когда данные мы бережём,
 *    снимать по ним напоминания стало прямо неправильно.
 *
 *  ЧЕГО ЭТО НЕ РЕШАЕТ (и не должно): человек, ИСКЛЮЧЁННЫЙ из компании,
 *  сохраняет локально запланированные напоминания с именами её клиентов —
 *  отзыв доступа до устройства не доезжает вовсе. Это отдельная, серверная
 *  задача. */
export function notificationsForWipe(opts: {
  keepLocalCache?: boolean;
}): WipeNotificationsPlan {
  return opts.keepLocalCache ? "none" : "clear";
}
