// «ЕЩЁ N» В ШАПКЕ БЛОКА (плашка «ещё» и количество: так видно, что есть ещё,
// допустим, три объекта). Карточка клиента показывает по одной вещи — последнюю
// запись, основной объект, последний файл, основные реквизиты; плашка
// говорит, сколько ещё лежит за тапом. Одна вещь — плашки нет.

export function moreLabel(total: number, shown = 1): string | null {
  const rest = total - shown;
  return rest > 0 ? `Ещё ${rest}` : null;
}
