import { formatCountRu, pluralRu } from "@babun/shared/common/utils/plural-ru";

// НЕОТПРАВЛЕННОЕ НЕ ПРОПАДАЕТ МОЛЧА (аудит 2026-10-03).
//
// Выход из аккаунта обязан стереть очередь правок вместе со всем кэшем: после
// выхода на устройстве не остаётся ни строки — это межтенантная защита, и она
// не обсуждается. Но правки, набранные без сети и ещё не ушедшие, стирались
// без единого слова — в том числе правки ДРУГОЙ компании человека: под
// текущей они не уходят и в «Синхронизации» не видны. Теперь выход сначала
// говорит, сколько пропадёт, и ждёт «Выйти».

/** Фраза для подтверждения выхода; null — терять нечего. */
export function unsentChangesNote(depth: number): string | null {
  if (!(depth > 0)) return null;
  const count = formatCountRu(depth, ["изменение", "изменения", "изменений"]);
  const wait = pluralRu(depth, ["ждёт", "ждут", "ждут"]);
  const lost = pluralRu(depth, ["оно пропадёт", "они пропадут", "они пропадут"]);
  return `${count} ${wait} отправки — после выхода ${lost} с этого телефона.`;
}
