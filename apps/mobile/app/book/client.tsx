// Это ТА ЖЕ карточка клиента, что `/clients/new` (владелец 2026-08-31:
// «как в клиентах» — второй формы создания клиента не бывает), только
// открытая маршрутом корневого стека, сиблингом самой записи. Причина в
// навигации, а не в дизайне: `/clients/new` живёт внутри вкладки «Клиенты»,
// и переход туда из записи клал поверх неё вторую копию табов — «назад»
