// Тот же экран, что в Кабинете, но открытый маршрутом стека `/book`,
// сиблингом самой формы. Причина навигационная, ровно та же, что у карточки
// клиента (`/book/client`) и типов событий (`/book/event-types`):
// `/cabinet/services` живёт внутри ВКЛАДКИ «Кабинет», и push туда из формы
// клал бы поверх неё вторую копию табов — «назад» уводил бы на календарь, а
// форма со всем набранным осталась бы висеть под ним.
//
// Дверь нужна из-за ПУСТОГО ПРАЙСА: у новой компании и у команды, которой при
// разделении ничего не досталось, лист выбора услуг пуст, и завести услугу
// было можно только уйдя в Кабинет и потеряв набранную запись. Второй формы
// услуги при этом не появляется — по закону «короткая форма это лист,
// сущность-владелец это страница» услуга правится своей страницей, и это она.
