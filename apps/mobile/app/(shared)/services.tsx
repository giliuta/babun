import ServicesScreen from "../(dashboard)/cabinet/services";

// УСЛУГИ ИЗ ФОРМЫ ЗАПИСИ — ПОВЕРХ ФОРМЫ, А НЕ ВМЕСТО НЕЁ.
//
// Тот же экран, что в Кабинете, но с адресом в группе `(shared)` — над
// табами, сиблингом того, кто его позвал: услуги нужны и записи, и форме
// операции. `/cabinet/services` живёт внутри ВКЛАДКИ «Кабинет», и push туда
// с экрана над табами клал бы поверх него вторую копию табов — «назад»
// уводил бы на календарь, а форма со всем набранным осталась бы висеть под
// ним.
//
// Дверь нужна из-за ПУСТОГО ПРАЙСА: у новой компании и у команды, которой при
// разделении ничего не досталось, лист выбора услуг пуст, и завести услугу
// было можно только уйдя в Кабинет и потеряв набранную запись. Второй формы
// услуги при этом не появляется — по закону «короткая форма это лист,
// сущность-владелец это страница» услуга правится своей страницей, и это она.
export default function BookServicesScreen() {
  return <ServicesScreen />;
}
