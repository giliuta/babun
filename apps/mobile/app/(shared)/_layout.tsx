import { Platform } from "react-native";
import { Stack } from "expo-router";
import { useSafeAreaInsets } from "react-native-safe-area-context";
import { useThemeColors } from "@/theme/colors";
import { DashboardGate } from "@/lib/DashboardGate";

// ОДИН ЭКРАН НА ВСЕХ, КТО ЕГО ЗОВЁТ.
//
// Владелец 2026-09-10: «не создавай новую страницу для записи, бери ту, что мы
// и так используем… добавить клиента открывает одну единую страницу для всех,
// и неважно откуда: из клиентов, из календаря в записи или из финансов —
// всегда одна и та же. Вот это чистая архитектура».
//
// Экран здесь ровно один на каждый предмет — карточка клиента, способы связи,
// карты, типы объектов, — и это ТЕ ЖЕ экраны, что во вкладке «Клиенты»
// (файлы отсюда их и импортируют). Разный только АДРЕС, и разный он по
// навигационной причине: `/clients/*` живёт ВНУТРИ вкладки, и переход туда с
// экрана, который лежит НАД табами (запись, финансы), кладёт поверх него
// вторую копию табов — «назад» уводит в список клиентов, а запись со всем
// набранным исчезает (владелец 2026-09-04: «жму назад — и закрывается; назад
// всегда должно перекидывать на запись»).
//
// Раньше эти адреса лежали в `app/book/*` и назывались «из записи». Теперь ту
// же карточку зовут финансы (шторка долга), и слово «book» стало враньём:
// группа — не про запись, а про «поверх позвавшего».
export default function SharedLayout() {
  const t = useThemeColors();
  const insets = useSafeAreaInsets();
  return (
    <DashboardGate>
      <Stack
        screenOptions={{
          headerShown: false,
          // НИЗ — НАД НАВИГАЦИЕЙ ANDROID (13.10). Экраны группы — те же, что во
          // вкладках (`Screen edges={["top"]}`): там низ закрывает таб-бар, а
          // здесь, над табами, подвал («Создать услугу», «Создать клиента»)
          // ложился под «Назад / Домой» и почти не нажимался. На iOS вид
          // прежний.
          contentStyle: {
            backgroundColor: t.canvas,
            paddingBottom: Platform.OS === "android" ? insets.bottom : 0,
          },
        }}
      />
    </DashboardGate>
  );
}
