import { Stack } from "expo-router";
import { useThemeColors } from "@/theme/colors";

// ВКЛАДКА «КАЛЕНДАРЬ» — СТЕК ВНУТРИ ТАБА, КАК «КЛИЕНТЫ» И «ФИНАНСЫ».
//
// До 2026-08-20 настройки календаря лежали КОРНЕВЫМ стеком поверх табов, и
// таб-бар из-под них исчезал: зайдя в «Услуги», человек терял и «Финансы», и
// «Клиентов» — выйти можно было только назад по стрелке. Владелец: «внизу
// должен всё равно быть этот бар… тапаю на финансы — перехожу в финансы,
// тапаю обратно на календарь — возвращаюсь на ту же страницу, где был».
//
// Стек внутри вкладки даёт ровно это и бесплатно: каждая вкладка помнит свою
// глубину, таб-бар живёт под всеми экранами, а повторный тап по своей же
// вкладке разматывает её до корня (см. tabPress в ../_layout.tsx).
//
// Группа `(home)`, а не каталог `calendar`: скобки не попадают в адрес, так
// что календарь остаётся на «/», а его настройки — на «/calendar/*». Ни один
// диплинк и ни одна ссылка в продукте от переезда не поменялись.
export default function HomeStackLayout() {
  const t = useThemeColors();
  return (
    <Stack
      screenOptions={{
        headerShown: false,
        contentStyle: { backgroundColor: t.canvas },
      }}
    />
  );
}
