import { Stack } from "expo-router";
import { useThemeColors } from "@/theme/colors";

// ГЛАВНЫЙ ЭКРАН ВКЛАДКИ ВСЕГДА ПОД ЛЮБЫМ ЕЁ ЭКРАНОМ (иначе «назад» из
// вкладки перекидывает на предыдущую). Экран
// вкладки, открытый снаружи — из календаря, из формы, дверью листа, по
// ссылке, — ложился в стек вкладки ОДИН, без её корня под собой, и «назад»
// уходил из вкладки на предыдущую. `initialRouteName` кладёт корень вниз
// при любом входе в стек; сторож — `tab-stack-roots.test.ts`.
export const unstable_settings = { initialRouteName: "index" };

// ВКЛАДКА «КАЛЕНДАРЬ» — СТЕК ВНУТРИ ТАБА, КАК «КЛИЕНТЫ» И «ФИНАНСЫ».
//
// Настройки календаря корневым стеком поверх табов прятали бы таб-бар: зайдя
// в «Услуги», человек терял бы и «Финансы», и «Клиентов» — выйти можно было
// бы только назад по стрелке. Таб-бар должен быть всегда, а возврат на
// вкладку — приводить на ту же страницу.
//
// Стек внутри вкладки даёт это бесплатно: каждая вкладка помнит свою
// глубину, таб-бар живёт под всеми экранами, а повторный тап по своей же
// вкладке разматывает её до корня (см. tabPress в ../_layout.tsx).
//
// Группа `(home)`, а не каталог `calendar`: скобки не попадают в адрес, так
// что календарь остаётся на «/», а его настройки — на «/calendar/*». Ни один
// диплинк и ни одна ссылка в продукте от переезда не поменялись.
export default function HomeStackLayout() {
  const t = useThemeColors();
  return (
    <Stack
      screenOptions={{
        headerShown: false,
        contentStyle: { backgroundColor: t.canvas },
      }}
    />
  );
}
