import { useLocalSearchParams } from "expo-router";
import { LabelsScreen } from "@/features/reference/screens/LabelsScreen";

// МЕТКИ КОМАНДЫ — ТОТ ЖЕ ЭКРАН, ЧТО И В НАСТРОЙКАХ КАЛЕНДАРЯ.
//
// До 2026-08-29 здесь жил СВОЙ экран на 440 строк: он правил `teams.cities` —
// список ИМЁН, подобранных команде из общего справочника. Это был подбор, а
// не владение: справочник оставался общим, две команды не могли завести
// разные метки с одинаковым именем, а «свои метки» существовали только как
// фильтр поверх чужого списка.
//
// Владелец 2026-08-29: «метка закрепляется за командой — то же самое, как
// график, как услуга; нельзя поставить метку в другую команду». Теперь у
// метки есть колонка `team_id`, и подбор стал не нужен: список команды и
// ЕСТЬ её метки. Одна поверхность на обе двери — как у услуг.
export default function TeamLabelsRoute() {
  const { id } = useLocalSearchParams<{ id?: string }>();
  const teamId = Array.isArray(id) ? id[0] : id;
  return <LabelsScreen teamId={teamId ?? null} />;
}
