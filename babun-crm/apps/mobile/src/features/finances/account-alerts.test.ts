import assert from "node:assert/strict";
import { describe, test } from "node:test";
import { cashCountErrorText } from "./account-alerts";

describe("ошибка пересчёта кассы человеческим языком", () => {
  test("закрытый день объясняет ПОРЯДОК, а не запрет", () => {
    const text = cashCountErrorText(
      "Финансы до 10.08.2026 закрыты. Сначала откройте день обратно",
    );
    assert.match(text, /10\.08\.2026/);
    assert.match(text, /сначала пересчитывают кассы, потом/);
    // Сырого текста стража в подписи не остаётся: он отвечает на другой
    // вопрос («почему нельзя»), а не на нужный («что теперь делать»).
    assert.doesNotMatch(text, /откройте день обратно$/);
  });

  test("незнакомая ошибка сервера проходит как есть", () => {
    // Owner-only функции отвечают по-русски и знают то, чего клиент не знает,
    // — перефразировать их наугад значит потерять причину.
    assert.equal(
      cashCountErrorText("Пересчитать можно только наличные"),
      "Пересчитать можно только наличные",
    );
  });
});
