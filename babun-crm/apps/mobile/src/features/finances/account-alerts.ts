// человек читал разное предупреждение об одном и том же действии, в
// зависимости от того, с какого экрана пришёл.
//
// Правила текстов (оттуда же): заголовок — короткий вопрос или состояние;
// тело — ПОСЛЕДСТВИЕ, а не оправдание; кнопка — глагол действия («Закрыть» в
// системном алерте iOS читается как «закрыть это окно», поэтому глагол всегда
// с существительным); «Отмена» первой; кнопок «ОК» и «Да» в продукте нет.

import { money, moneySign } from "@babun/shared/common/utils/money";

export interface AlertText {
  title: string;
  message: string;
  /** Подпись деструктивной кнопки. Без неё диалог — просто сообщение. */
  confirm?: string;
}

/** Мягкое закрытие: обратимо и сохраняет историю — об этом и говорим. */
export function closeAccountAlert(name: string): Required<AlertText> {
  return {
    title: "Закрыть счёт?",
    message:
      `«${name}» исчезнет из форм оплаты — принимать на него деньги будет `
      + "нельзя. Операции и остаток останутся в истории, счёт можно открыть "
      + "снова.",
    confirm: "Закрыть счёт",
  };
}

/**
 * Жёсткое удаление: счёт без единой операции. Слово «навсегда» обязательно.
 *
 * СУММУ НАЗЫВАЕМ, ЕСЛИ ОНА ЕСТЬ. «Не прошло ни одной операции» человек читает
 * как «там пусто», но остаток на начало операцией не является: счёт, заведённый
 * с €500 и ни разу не тронутый, уносит эти €500 из «Всего денег» молча.
 */
export function deleteAccountAlert(
  name: string,
  balance = 0,
): Required<AlertText> {
  const hasMoney = moneySign(balance) !== 0;
  return {
    title: "Удалить счёт?",
    message: hasMoney
      ? `По «${name}» не прошло ни одной операции, но на нём записано `
        + `${money(balance)}. Удаляем насовсем — эта сумма исчезнет и из `
        + "«Всего денег». Восстановить будет нечего."
      : `По «${name}» не прошло ни одной операции — удаляем насовсем, `
        + "восстановить будет нечего.",
    confirm: "Удалить счёт",
  };
}

/**
 * Предусловие закрытия: на счёте остались деньги. Текст называет СУММУ и
 * последствие («пропадут из общего остатка»), а не запрет.
 *
 * `canTransfer` — есть ли куда переводить: у тенанта с единственным счётом
 * законной пары может не быть вовсе, и обещать кнопку «Перевести» в такой
 * ситуации нельзя.
 */
export function accountNotEmptyAlert(
  name: string,
  balance: number,
  canTransfer: boolean,
): AlertText {
  const amount = money(balance);
  // МИНУС — НЕ «ОСТАЛИСЬ ДЕНЬГИ». Переводить с такого счёта нечего, и кнопка
  // «Перевести −€120» отбилась бы проверкой суммы. Совет обратный: сначала
  // провести приход, и только потом закрывать.
  if (moneySign(balance) < 0) {
    return {
      title: "Счёт в минусе",
      message:
        `На «${name}» ${amount}. Закрыть можно только счёт с нулём — сначала `
        + "проведите приход на эту сумму.",
    };
  }
  return {
    title: "На счёте остались деньги",
    message: canTransfer
      ? `На «${name}» ${amount}. Закрыть можно только пустой счёт — иначе эти `
        + "деньги пропадут из общего остатка. Переведите их на другой счёт или "
        + "спишите операцией."
      : `На «${name}» ${amount}. Закрыть можно только пустой счёт. Спишите `
        + "остаток операцией.",
    confirm: `Перевести ${amount}`,
  };
}

