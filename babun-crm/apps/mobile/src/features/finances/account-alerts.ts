/** «Финансы до 10.08.2026 закрыты. Сначала откройте день обратно» — текст
 *  общего стража леджера. Человеку с деньгами в руках он не объясняет
 *  ГЛАВНОГО: пересчёт кассы пишется сегодняшним числом, и порядок ритуала
 *  обратный тому, что он сделал. */
const CLOSED_DAY_RE = /Финансы до ([\d.]+) закрыты/;

/** Ошибка пересчёта кассы человеческим языком. Незнакомый текст сервера
 *  проходит как есть: owner-only функции отвечают по-русски и знают то, чего
 *  клиент не знает. */
export function cashCountErrorText(message: string): string {
  const match = CLOSED_DAY_RE.exec(message);
  if (!match) return message;
  return (
    `День ${match[1]} уже закрыт, а пересчёт кассы записывается сегодняшним `
    + "числом. Откройте день обратно: сначала пересчитывают кассы, потом "
    + "закрывают день."
  );
}

