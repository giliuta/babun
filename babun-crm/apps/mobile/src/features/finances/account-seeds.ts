// АВТОСОЗДАНИЕ СЧЕТОВ — ЧТО ЗАВОДИТСЯ САМО И КАКИМИ СЛОВАМИ (ТЗ §5.1).
//
// Команда без счёта не может принять деньги ВООБЩЕ — это поломка, а не выбор
// пользователя, поэтому тумблера у автосоздания нет: новой команде заводятся
// «Наличные» и «Карта». Сида «счетов компании» здесь больше нет: счёт
// принадлежит ровно одной команде (владелец 2026-08-15), и заводить общий
// счёт стало некому.
//
// ИМЯ ОДНО НА ПРОДУКТ — «Наличные». Веб-автосид заводил «Наличку», мобильная
// цепочка «команда → счёт» подставляла «Кассу», и в одном тенанте уживались
// три слова для одной сущности (аудит 2026-08-10). Глоссарий ТЗ §7 называет
// виды «Наличные · Карта · Банк · Другое» — берём ровно их: имя по умолчанию
// совпадает с названием вида, и не надо гадать, «Касса» — это наличные или
// счёт в банке.
//
// ПЛАНИРОВАНИЕ ОТДЕЛЕНО ОТ ЗАПИСИ: что именно заводить — чистая функция с
// тестом, сеть живёт в мутации (`accounts.ts`). Заодно это даёт автосозданию
// идемпотентность: повторный вызов после обрыва дозаводит недостающее, а не
// плодит второй счёт с тем же именем.

import type { AccountKind } from "@babun/shared/local/finance/account";

/** Счёт, который автосоздание заводит по умолчанию. */
export interface AccountSeed {
  name: string;
  kind: AccountKind;
}

/** Новая команда: деньги приходят наличными и на карту. */
export const TEAM_ACCOUNT_SEEDS: readonly AccountSeed[] = [
  { name: "Наличные", kind: "cash" },
  { name: "Карта", kind: "card" },
];

/** Что нужно знать о заведённом счёте, чтобы не завести его второй раз. */
export interface ExistingSeedTarget {
  brigade_id: string | null;
  name: string;
  position: number;
}

export interface PlannedAccount extends AccountSeed {
  /** Явная позиция в пределах (тенант, команда): 0, 1, 2… (ТЗ §5.1). */
  position: number;
}

const norm = (name: string): string => name.trim().toLowerCase();

/**
 * Каких счетов группе не хватает и с какими позициями их заводить.
 *
 * Группа — это пара (scope, brigade_id): позиции нумеруются внутри команды, и
 * «Наличные» соседней команды созданию ничему не мешают. Закрытые счета из
 * группы НЕ выбрасываются: имя занято и ими (в базе уникальность про
 * `is_active` не знает), а второй счёт «Наличные» рядом с закрытым — не то,
 * чего человек хотел, даже если бы база это пропустила.
 */
export function planAccountSeeds({
  seeds,
  existing,
  brigadeId,
}: {
  seeds: readonly AccountSeed[];
  /** Все счета тенанта, включая закрытые. */
  existing: readonly ExistingSeedTarget[];
  brigadeId: string | null;
}): PlannedAccount[] {
  // Группа — это БРИГАДА и только она: охват `scope` из продукта снесён
  // (владелец 2026-08-15), и сравнивать по нему значило бы делить один и тот
  // же список надвое по мёртвой колонке.
  const group = existing.filter(
    (account) => (account.brigade_id ?? null) === (brigadeId ?? null),
  );
  const taken = new Set(group.map((account) => norm(account.name)));
  // Пустая группа даёт ровно 0, 1, 2 — как требует ТЗ; непустая продолжает
  // нумерацию с конца, чтобы дозаведённый счёт встал последним, а не влез в
  // середину чужого порядка.
  let position = group.reduce(
    (max, account) => Math.max(max, account.position),
    -1,
  );
  const plan: PlannedAccount[] = [];
  for (const seed of seeds) {
    if (taken.has(norm(seed.name))) continue;
    position += 1;
    plan.push({ ...seed, position });
  }
  return plan;
}
