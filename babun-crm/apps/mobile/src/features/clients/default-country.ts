import type { CountryCode } from "libphonenumber-js";
import { useTenant } from "@/features/settings/tenant";
import { normalizeCountry } from "@/features/clients/phone";

// КОД СТРАНЫ ПО УМОЛЧАНИЮ — свойство КОМПАНИИ, а не команды и не устройства.
//
// Владелец 2026-07-26: «код страны надо, чтобы он был сразу автоматически, и в
// настройках чтобы можно было сразу выбирать… не команды, командами не
// получится… а если работать по разным странам — надо это продумать».
//
// Почему не команда: у одной бригады могут быть клиенты из разных стран, а
// номер принадлежит КЛИЕНТУ, не бригаде. Почему не устройство: тогда у
// владельца и у диспетчера новые клиенты заводились бы с разными кодами, и
// ключ дедупа phone_e164 расходился бы между телефонами.
//
// Поэтому источник — `tenants.country` (колонка уже была и заполнена, миграция
// не нужна). Она же настраивается в «Личной информации» компании.
//
// РАБОТА ПО РАЗНЫМ СТРАНАМ решается не настройкой, а разбором: код страны —
// это только ПОДСТАВКА в пустое поле. Номер, введённый со своим «+», уважается
// как есть (tryToE164 читает код из самого номера), поэтому кипрская фирма
// спокойно заводит греческого клиента, ничего не переключая.

/** Код страны компании. Пока профиль не загрузился — дефолт продукта: поле
 *  ввода не должно ждать сети, чтобы показать «+357». */
export function useDefaultCountry(): CountryCode {
  const { data: tenant } = useTenant();
  return normalizeCountry(tenant?.country);
}
