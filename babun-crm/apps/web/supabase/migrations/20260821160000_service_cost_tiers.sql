-- РАСХОД ЧЕТВЁРТОЙ КОЛОНКОЙ (владелец 2026-08-21: «надо четвёртое — добавляй
-- новую строчку, расход; стандарт будет ноль, человек сам выставляет свой
-- расход… короче делай ещё расход колонку»).
--
-- Первая строка услуги пишет в существующую `cost_per_unit`. Строки от
-- количества — сюда, зеркалом `price_tiers` до буквы:
-- [{"min_qty": 3, "cost_per_unit": 8}], min_qty целое >= 2.
--
-- ПОЧЕМУ НЕ ВНУТРЬ price_tiers, хотя это дешевле на миграцию:
--   1. `parsePriceTiers` выбрасывает элемент без валидной цены — строка, где
--      заполнен ТОЛЬКО расход, исчезла бы при первом же чтении вместе с деньгами;
--   2. `price_tiers` отдаётся проекции диспетчера, которая специально затирает
--      `cost_per_unit`, — положив расход туда, мы отправили бы маржу владельца
--      каждому диспетчеру через ту самую проекцию, которая её прячет;
--   3. колонка с именем «цены», хранящая себестоимость, — ложь в схеме.
--
-- В ПРОЕКЦИИ РОЛЕЙ НЕ ПОЯВЛЯЕТСЯ НИ У ДИСПЕТЧЕРА, НИ У МАСТЕРА: себестоимость
-- — дело владельца, обе RPC остаются как есть, оба маппера получают пустой
-- массив в ту же пару строк, где уже стоит `cost_per_unit: 0`.
alter table public.services
  add column if not exists cost_tiers jsonb not null default '[]'::jsonb;
