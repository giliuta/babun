-- ПРАЙС НЕ ПУБЛИКУЕТСЯ САМ.
--
-- `services.online_enabled` заведена июньской миграцией с `default true`, и на
-- проде она стоит ИСТИНОЙ у всех шести услуг — при том, что онлайн-записи в
-- продукте не существует: ни публичной страницы, ни ссылки, ни единого
-- читателя этой колонки. То есть галку никто не ставил, её поставил дефолт.
--
-- Цена ошибки видна только в день запуска: как только онлайн-запись появится,
-- весь прайс каждого тенанта опубликуется наружу сам, без ведома владельца —
-- вместе с ценами, которые он держал для своих. Публикация цен — решение
-- человека, и «по умолчанию опубликовано» такого решения не заменяет.
--
-- Чиним заранее, пока читателей нет и чинить дёшево: дефолт становится
-- ложью, existing строки гасятся. Ни один экран этого не заметит.
alter table public.services alter column online_enabled set default false;

update public.services set online_enabled = false where online_enabled;
