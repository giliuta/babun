type DbSupabase = SupabaseClient<Database>;

// v452 — UUID guard. The Supabase `appointments` table has `id` as
// uuid; sending the legacy local-storage id pattern (`apt-${ts}-rnd`,
// generated by `generateId("apt")`) makes Postgres reject the whole
// statement with «invalid input syntax for type uuid». That's how the
// PersonalEventSheet's create+delete cycle was poisoning the sync
// queue with unreplayable ops.
const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const isUuid = (s: string): boolean => UUID_RE.test(s);

// ─── Read ─────────────────────────────────────────────────────────

export async function listAppointments(
  supabase: DbSupabase,
  tenantId: string,
): Promise<Appointment[]> {
  const cached = await safeCacheReadAppointments(tenantId);
  if (cached.length > 0) {
    void revalidateAppointments(supabase, tenantId);
    return cached.map(rowToAppointment);
  }
  // Cold-OFFLINE guard (offline-plan rule 4): empty cache + no network →
  // `repoListAppointments` throws. Catch and return [] so the calendar shows
  // an empty grid, not an error screen (matches tagsCached / clientsCached).
  try {
    const fresh = await repoListAppointments(supabase, tenantId);
    await refreshCacheFromSupabase(supabase, tenantId, fresh).catch(() => {});
    return fresh;
  } catch {
    return [];
  }
}

async function revalidateAppointments(
  supabase: DbSupabase,
  tenantId: string,
): Promise<void> {
  try {
    const changed = await refreshCacheFromSupabase(supabase, tenantId);
    // Emit only on a real change (loop guard — see revalidate-events).
    if (changed) emitRevalidated("appointments");
  } catch {
    // ignore — cached list already returned
  }
}

/** Refill the cache with the canonical DOMAIN list. `repoListAppointments`
 *  already maps every jsonb column into its domain shape; we only decorate
 *  each with `tenant_id` (the one bookkeeping key the domain drops — `date`
 *  + `updated_at` are already on the Appointment). Callers on the cold path
 *  pass the already-fetched list to avoid a second round-trip.
 *
 *  Slice 5 — AUTHORITATIVE + REVALIDATE-BRIDGE. `cacheReplaceTenant` prunes
 *  appointments deleted on another device; the signature diff drives the
 *  bridge emit (returns whether anything changed). */
async function refreshCacheFromSupabase(
  supabase: DbSupabase,
  tenantId: string,
  domain?: Appointment[],
): Promise<boolean> {
  const appts = domain ?? (await repoListAppointments(supabase, tenantId));
  const rows = appts.map((a) => makeCachedRow(a, tenantId));
  const before = cacheSignature(await safeCacheReadAppointments(tenantId));
  await cacheReplaceTenant("appointments", tenantId, rows);
  const after = cacheSignature(rows);
  return before !== after;
}

// Cache row → domain. The cache stores the full domain object decorated
// with tenant_id; strip it and return a clean `Appointment` (identical to
// what the repo list returns).
function rowToAppointment(r: CachedAppointmentData): Appointment {
  const { tenant_id: _t, ...appointment } = r;
  void _t;
  return appointment;
}

/** Build the DOMAIN cache row (what lands in `data`) from a canonical
 *  `Appointment`. Nested fields verbatim + the tenant_id bookkeeping key.
 *  `date` + `updated_at` are already on the domain object (the SQL layer
 *  reads them off the top level for its denorm columns). */
function makeCachedRow(
  appointment: Appointment,
  tenantId: string,
): CachedAppointmentData {
  return { ...appointment, tenant_id: tenantId };
}

// ─── Write ────────────────────────────────────────────────────────

export async function createAppointment(
  supabase: DbSupabase,
  input: Appointment,
  tenantId: string,
): Promise<Appointment> {
  const id = input.id || randomUuid();
  const nowIso = new Date().toISOString();
  // Two projections (rule 4):
  //   cachedRow — full DOMAIN object for reads.
  //   serverRow — raw DB columns for the queue payload the replayer INSERTs.
  const cachedRow = makeCachedRow(
    { ...input, id, created_at: input.created_at || nowIso, updated_at: nowIso },
    tenantId,
  );
  const serverRow = makeServerRow(input, tenantId, id, nowIso);
  const insertOp = {
    table: "appointments" as const,
    op: "insert" as const,
    row_id: id,
    payload: serverRow as unknown as Record<string, unknown>,
    expected_updated_at: null,
  };

  if (isOnline()) {
    // Optimistic UI first (standalone online — no queued op to pair with).
    await cacheUpsert("appointments", cachedRow);
    try {
      const created = await repoCreateAppointment(
        supabase,
        { ...input, id },
        tenantId,
      );
      // v452 — rebind cache from the optimistic local-id row to the
      // canonical UUID Supabase allocated. Without this, the cache
      // accumulates orphan "apt-XXX" rows alongside the real ones,
      // and a later delete on the orphan poisons the sync queue.
      if (created.id !== id) {
        try {
          await cacheDelete("appointments", id);
        } catch {
          /* ignore — cache may not have stored the optimistic row */
        }
      }
      await refetchAndCacheOne(supabase, created.id, tenantId);
      return created;
    } catch (err) {
      // Network blip — ATOMIC optimistic upsert + enqueue (risk #6).
      void err;
      await enqueueOpWithCacheUpsertAndEmit(insertOp, "appointments", cachedRow);
      void kickReplayer({ supabase });
      return { ...input, id };
    }
  }

  // Offline — ATOMIC optimistic upsert + enqueue (risk #6).
  await enqueueOpWithCacheUpsertAndEmit(insertOp, "appointments", cachedRow);
  return { ...input, id };
}

export async function updateAppointment(
  supabase: DbSupabase,
  id: string,
  patch: Partial<Appointment>,
  tenantId: string,
): Promise<Appointment> {
  const existing = await readCachedAppointment(id, tenantId);
  const expectedUpdatedAt = existing?.updated_at ?? null;

  // Optimistic cache merge is DOMAIN-shaped (patch applied to the full
  // domain object); the queue payload stays the raw-column projection.
  const merged: CachedAppointmentData | null = existing
    ? {
        ...existing,
        ...patch,
        updated_at: new Date().toISOString(),
      }
    : null;

  // v452 — non-UUID ids never made it to Supabase. Skip the network +
  // queue path entirely; the optimistic cache write IS the full story, so
  // it stays a standalone upsert (there is no queued op to pair with).
  if (!isUuid(id)) {
    if (merged) await cacheUpsert("appointments", merged);
    return { ...toDomain(existing), ...patch, id } as Appointment;
  }

  const updateOp = {
    table: "appointments" as const,
    op: "update" as const,
    row_id: id,
    payload: patchToRow(patch) as Record<string, unknown>,
    expected_updated_at: expectedUpdatedAt,
  };

  if (isOnline()) {
    // Online: standalone optimistic upsert (no queued op to pair with).
    if (merged) await cacheUpsert("appointments", merged);
    try {
      const updated = await repoUpdateAppointment(
        supabase,
        id,
        patch,
        tenantId,
      );
      await refetchAndCacheOne(supabase, id, tenantId);
      return updated;
    } catch (err) {
      void err;
      await enqueueUpdate(updateOp, merged);
      void kickReplayer({ supabase });
      return { ...toDomain(existing), ...patch, id } as Appointment;
    }
  }

  // Offline — ATOMIC with the optimistic row when cached (risk #6).
  await enqueueUpdate(updateOp, merged);
  return { ...toDomain(existing), ...patch, id } as Appointment;
}

/** Domain view of a cached row (drops the tenant_id bookkeeping key), or an
 *  empty base when the row wasn't cached. */
function toDomain(existing: CachedAppointmentData | null): Partial<Appointment> {
  return existing ? rowToAppointment(existing) : {};
}

/** Enqueue an update op, pairing it in one exclusive transaction with the
 *  optimistic merged row when there is one (risk #6). merged === null (row
 *  not cached) → plain emit-enqueue, matching the prior `if (existing)`. */
async function enqueueUpdate(
  op: Parameters<typeof enqueueOpAndEmit>[0],
  merged: CachedAppointmentData | null,
): Promise<void> {
  if (merged) {
    await enqueueOpWithCacheUpsertAndEmit(op, "appointments", merged);
  } else {
    await enqueueOpAndEmit(op);
  }
}

export async function deleteAppointment(
  supabase: DbSupabase,
  id: string,
  tenantId: string,
): Promise<void> {
  // v452 — non-UUID ids are local orphans (the row never made it to
  // Supabase because an earlier insert failed). Skip the network + queue
  // entirely so we don't keep re-enqueueing dead ops — a standalone
  // cacheDelete is the full story (no queued op to pair with).
  if (!isUuid(id)) {
    await cacheDelete("appointments", id);
    return;
  }

  const deleteOp = {
    table: "appointments" as const,
    op: "delete" as const,
    row_id: id,
    payload: { id, tenant_id: tenantId },
    expected_updated_at: null,
  };

  if (isOnline()) {
    await cacheDelete("appointments", id); // optimistic (standalone online)
    try {
      await repoDeleteAppointment(supabase, id, tenantId);
      return;
    } catch {
      // Fall through — ATOMIC optimistic delete + enqueue (risk #6).
      await enqueueOpWithCacheDeleteAndEmit(deleteOp, "appointments", id);
      void kickReplayer({ supabase });
      return;
    }
  }

  // Offline — ATOMIC optimistic delete + enqueue (risk #6).
  await enqueueOpWithCacheDeleteAndEmit(deleteOp, "appointments", id);
}

// ─── Helpers ──────────────────────────────────────────────────────

async function safeCacheReadAppointments(
  tenantId: string,
): Promise<CachedAppointmentData[]> {
  try {
    return await cacheRead<CachedAppointmentData>("appointments", tenantId);
  } catch {
    return [];
  }
}

async function readCachedAppointment(
  id: string,
  tenantId?: string,
): Promise<CachedAppointmentData | null> {
  try {
    // Tenant-scope the single-row read to the active tenant (minor: avoids
    // reading a row of another of the user's tenants on an id collision).
    return await cacheGetOne<CachedAppointmentData>("appointments", id, tenantId);
  } catch {
    return null;
  }
}

/** After a successful server write, refresh the cache with the CANONICAL
 *  domain row via `repoGetAppointment` (maps every jsonb column to its
 *  domain shape + carries the server's updated_at). */
async function refetchAndCacheOne(
  supabase: DbSupabase,
  id: string,
  tenantId: string,
): Promise<void> {
  const appt = await repoGetAppointment(supabase, id, tenantId).catch(() => null);
  if (!appt) return;
  await cacheUpsert("appointments", makeCachedRow(appt, tenantId));
}

function makeServerRow(
  input: Appointment,
  tenantId: string,
  id: string,
  nowIso: string,
): CachedAppointment {
  return {
    id,
    tenant_id: tenantId,
    client_id: input.client_id ?? null,
    team_id: input.team_id ?? null,
    master_id: input.master_id ?? null,
    location_id: input.location_id ?? null,
    date: input.date,
    time_start: input.time_start,
    time_end: input.time_end,
    kind: input.kind ?? "work",
    status: input.status ?? "scheduled",
    total_amount: input.total_amount ?? 0,
    custom_total: input.custom_total ?? false,
    discount_amount: input.discount_amount ?? 0,
    prepaid_amount: input.prepaid_amount ?? 0,
    comment: input.comment ?? "",
    address: input.address ?? "",
    address_note: input.address_note ?? "",
    address_lat: input.address_lat ?? null,
    address_lng: input.address_lng ?? null,
    cancel_reason: input.cancel_reason ?? null,
    source: input.source ?? null,
    is_online_booking: input.is_online_booking ?? false,
    consent_given: input.consent_given ?? true,
    color_override: input.color_override ?? null,
    reminder_enabled: input.reminder_enabled ?? false,
    reminder_offsets: (input.reminder_offsets ?? []) as unknown as CachedAppointment["reminder_offsets"],
    reminder_template: input.reminder_template ?? "",
    service_ids: (input.service_ids ?? []) as unknown as CachedAppointment["service_ids"],
    services: (input.services ?? []) as unknown as CachedAppointment["services"],
    service_price_overrides: (input.service_price_overrides ?? {}) as unknown as CachedAppointment["service_price_overrides"],
    expenses: (input.expenses ?? []) as unknown as CachedAppointment["expenses"],
    payments: (input.payments ?? []) as unknown as CachedAppointment["payments"],
    payment: (input.payment ?? null) as CachedAppointment["payment"],
    global_discount: (input.global_discount ?? null) as CachedAppointment["global_discount"],
    total_duration: input.total_duration ?? 0,
    payment_status: input.payment_status ?? "unpaid",
    payment_method: input.payment_method ?? null,
    paid_amount: input.paid_amount ?? 0,
    // STORY-055 — created_by is filled server-side by the BEFORE
    // INSERT trigger; the optimistic cache row carries null and gets
    // rewritten on refetchAndCacheOne after the real insert.
    created_by: null,
    created_at: input.created_at ?? nowIso,
    updated_at: nowIso,
    // Event-mode fields (personal calendar). All have safe defaults so
    // a non-event appointment slots in as a regular work record.
    event_all_day: input.event_all_day ?? false,
    event_notes: input.event_notes ?? "",
    event_url: input.event_url ?? "",
    event_push_enabled: input.event_push_enabled ?? false,
    event_push_offsets: (input.event_push_offsets ?? []) as unknown as CachedAppointment["event_push_offsets"],
    event_push_at: input.event_push_at ?? null,
    event_repeat: (input.event_repeat ?? { kind: "none" }) as unknown as CachedAppointment["event_repeat"],
  };
}

