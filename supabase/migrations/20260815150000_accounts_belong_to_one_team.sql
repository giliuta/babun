-- СЧЁТ ПРИНАДЛЕЖИТ ОДНОЙ БРИГАДЕ. «ОБЩЕГО СЧЁТА» БОЛЬШЕ НЕТ.
--
-- Владелец 2026-08-15: «есть такое понятие как общий счёт — мы это понятие
-- полностью убираем, счёт компании полностью сотри, он вообще не нужен; счёт
-- создаётся чётко на каждую команду. Упростить всё максимально».
--
-- ЧТО ЭТО БЫЛО. `scope='company'` + таблица `account_teams` описывали счёт,
-- которым пользуются несколько бригад. Из него же росло правило перевода
-- «между бригадами деньги идут через счёт, подключённый к обеим» — то есть
-- ЦЕЛЫЙ ЗАПРЕТ существовал только ради этой сущности. Убирая её, мы убираем и
-- запрет: перевод идёт между любыми двумя счетами напрямую.
--
-- ФАКТУРА НА МОМЕНТ МИГРАЦИИ (проверено запросом по всей базе):
--   общих счетов ВО ВСЕЙ БАЗЕ — один: «Revolut Business» тенанта Giliuta,
--   подключён ровно к ОДНОЙ бригаде и держит три проводки. Терять нечего:
--   он становится счётом этой бригады, и его деньги остаются на месте.
--
-- Схему НЕ ломаем: колонка `scope` и таблица `account_teams` остаются на
-- месте. Их читают серверные функции (`account_serves_team`,
-- `list_payment_accounts_safe`, `resolve_appointment_finance_account`), и для
-- счёта одной бригады они и так отвечают верно. Снос схемы — отдельный шаг
-- после того, как новый клиент доедет на все телефоны; переписывать функции
-- денег заодно с переносом данных нельзя.

-- ─── 1. Общий счёт становится счётом своей бригады ───────────────────
-- Бригада берётся из подключений. Их у такого счёта может быть несколько —
-- тогда берём первую по алфавиту, детерминированно: выбор «какой именно» тут
-- не важен, важно, что деньги остаются у кого-то конкретного и видны.
update public.accounts a
   set scope = 'team',
       brigade_id = (
         select at.team_id
           from public.account_teams at
          where at.account_id = a.id
          order by at.team_id
          limit 1
       ),
       updated_at = now()
 where a.scope = 'company'
   and exists (
     select 1 from public.account_teams at where at.account_id = a.id
   );

-- ─── 2. Подключения больше не описывают ничего ───────────────────────
-- У счёта одной бригады владелец записан в самой строке (`brigade_id`), и
-- строка в `account_teams` — второй источник правды о том же. Второй источник
-- правды о деньгах живёт ровно до первого расхождения.
delete from public.account_teams at
 using public.accounts a
 where at.account_id = a.id
   and a.scope = 'team';

-- ─── 3. Что осталось общим — осталось намеренно ──────────────────────
-- Счёт `scope='company'` БЕЗ единого подключения (в базе на 2026-08-15 таких
-- нет) не конвертируется: назначить ему бригаду не из чего, а выдумать —
-- значит отдать чужие деньги случайной команде. Такой счёт останется виден
-- только в архиве, и разбирать его владелец будет руками.
comment on column public.accounts.scope is
  'Историческая колонка. Живой продукт заводит только scope=''team'': счёт принадлежит одной бригаде (владелец 2026-08-15, «общий счёт убираем»).';
comment on table public.account_teams is
  'Историческая таблица подключений общего счёта к бригадам. Живой продукт её не пишет и не читает: у счёта один владелец — accounts.brigade_id.';
