-- МЕТКА У ОТДЕЛЬНОЙ ЗАПИСИ (владелец 2026-09-04).
--
-- «В день допустим есть целый день Лимассол, но последний клиент — мы можем
--  поставить другую метку. То есть целый день ребята работают на одной метке,
--  а в конце просто ставится другая метка.»
--
-- До сих пор метка существовала на ДВУХ уровнях: у дня команды
-- (`day_cities.city`) и у клиента (`clients.city`). Между ними не было
-- уровня, на котором живёт реальная работа, — самой записи. Диспетчеру
-- приходилось либо перекрашивать весь день, либо не отмечать вовсе.
--
-- NULL — «как у дня»: запись не спорит с днём и переезжает вместе с ним.
-- Строка — своя метка именно этой записи.
--
-- ИМЯ КОЛОНКИ `city`, как в `day_cities.city` и `clients.city`: один и тот же
-- предмет во всех трёх местах обязан называться одинаково, даже если слово
-- историческое (в продукте это «метка»).
alter table public.appointments
  add column if not exists city text;

comment on column public.appointments.city is
  'Метка ЭТОЙ записи. NULL — берётся метка дня команды (day_cities). Строкой хранится имя метки, как в day_cities.city и clients.city.';
