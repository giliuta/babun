-- ДОКУМЕНТ ПОД ДОЛГОМ. Владелец 2026-09-10: «добавь блок файл в долги».
--
-- Причина та же, что у операции (2026-08-09: «когда тратим расходы —
-- отсканировать инвойс, чтобы к каждой сумме был документ»): под долгом чаще
-- всего лежит бумага — накладная поставщика, расписка, счёт. Без неё через
-- месяц не вспомнить, за что висят деньги, а заметка на строку этого не
-- заменяет.
--
-- Колонка та же по смыслу и по имени, что у операции: путь в приватном бакете
-- чеков. Одно хранилище, один загрузчик, одна чистка сирот — второго способа
-- прикладывать бумагу в продукте быть не должно.
alter table public.debts
  add column if not exists receipt_url text;

comment on column public.debts.receipt_url is
  'Путь к документу в приватном бакете чеков — тот же, что у finance_transactions.receipt_url.';
