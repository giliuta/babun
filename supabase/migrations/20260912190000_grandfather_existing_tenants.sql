-- Кто работал в продукте ДО появления подписки — функции не теряет.
--
-- Дальше вводится бесплатный уровень: без подписки нельзя вести клиентские
-- записи, услуги, мастеров и документы (личный календарь, личные события,
-- личные финансы и база контактов остаются). Тариф в базе у ВСЕХ сегодня
-- `free` — включая боевые компании владельца. Если закрыть функции, не
-- сделав этого шага, продукт запрётся у тех, кто им пользуется каждый день:
-- человек откроет утром календарь и не сможет записать клиента.
--
-- `plan_override` для этого и заведён (STORY-052: «lifetime — ручная выдача,
-- AirFix one-shot»). Ставим его всем, кто ПРОШЁЛ онбординг: это ровно те, кто
-- завёл компанию и работает. Пустые смоук-аккаунты без онбординга не трогаем —
-- им бесплатный уровень и предназначен.
--
-- Правило шире одного случая и должно пережить эту миграцию: НОВОЕ ОГРАНИЧЕНИЕ
-- НЕ ПРИМЕНЯЕТСЯ ЗАДНИМ ЧИСЛОМ К ТЕМ, КТО УЖЕ РАБОТАЕТ. Снять обратно —
-- `update public.tenants set plan_override = null where id = …`.

update public.tenants
   set plan_override = 'lifetime'
 where onboarded_at is not null
   and plan_override is null;

do $$
declare
  v_open integer;
begin
  select count(*) into v_open
    from public.tenants
   where onboarded_at is not null
     and public.tenant_effective_plan(id) = 'free';

  if v_open > 0 then
    raise exception 'подписка: % работающих компаний осталось на бесплатном — их запрёт новым ограничением', v_open;
  end if;
end $$;
