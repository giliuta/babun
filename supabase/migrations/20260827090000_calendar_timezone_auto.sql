-- ЧАСОВОЙ ПОЯС БЕРЁТСЯ С ТЕЛЕФОНА (владелец 2026-08-27: «время автоматически
-- сделай как в iPhone»).
--
-- До этой миграции в дефолтах приложения была прибита Europe/Nicosia, а
-- Intl.DateTimeFormat().resolvedOptions().timeZone не вызывался в продукте ни
-- разу. Мастер в Варшаве жил по кипрским суткам, ни разу не открыв настройки:
-- «сегодня» в его кассе кончалось в 23:00 по его часам.
--
-- ПОРЯДОК ВАЖЕН. Колонка добавляется с DEFAULT true — его получают строки,
-- созданные ПОСЛЕ миграции. Действующие строки тут же переводятся в РУЧНОЙ
-- режим: их зона уже отвечает про конкретный бизнес, и переписывать её задним
-- числом нельзя — часовой пояс задаёт границы суток в кассе, в закрытии дня и
-- в отчётах, то есть сдвиг стоит выручки не в том дне.
alter table public.calendar_settings
  add column if not exists timezone_auto boolean not null default true;

update public.calendar_settings set timezone_auto = false;

comment on column public.calendar_settings.timezone_auto is
  'Пояс взят с устройства и следит за ним. Отдельное поле, а не признак внутри timezone: строку читают три десятка мест и сразу отдают в Intl.';
