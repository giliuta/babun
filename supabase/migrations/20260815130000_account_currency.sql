--
-- До этого валюта была одна на компанию (`tenants.currency`), и счёт в фунтах
-- завести было нечем. Теперь она стоит НА СЧЁТЕ: «Наличка» в евро и «Revolut
-- GBP» живут рядом.
--
-- NULL — ВАЛЮТА КОМПАНИИ. Так старые счета остаются верными без единой строчки
-- бэкфила, а «евро по умолчанию» не превращается в зашитую константу: сменит
-- компания валюту — за ней поедут и счета, которые про валюту молчат.
--
-- ⚠️ КУРСОВ ЗДЕСЬ НЕТ И НЕ БУДЕТ ПО УМОЛЧАНИЮ. Пересчитать фунты в евро без
-- курса на дату невозможно, а придуманный курс — это враньё про деньги на
-- главном экране. Поэтому правило продукта: суммы складываются только внутри
-- одной валюты, а счета в чужой показываются своей строкой. Курсы, если
-- понадобятся, — отдельная работа со своей таблицей и датой.

alter table public.accounts
  add column if not exists currency text;

-- Тот же пятёрочный набор, что у компании (`money.ts`, MoneyCurrency): один
-- список валют на весь продукт, иначе счёт можно завести в валюте, которую
-- приложение не умеет напечатать.
alter table public.accounts drop constraint if exists accounts_currency_check;
alter table public.accounts add constraint accounts_currency_check
  check (currency is null or currency in ('EUR', 'USD', 'RUB', 'UAH', 'GBP'));

comment on column public.accounts.currency is
  'Валюта счёта. NULL — валюта компании (tenants.currency). Курсов в продукте нет: суммы складываются только внутри одной валюты.';

