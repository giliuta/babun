-- РЕГИСТРАЦИЯ ПО ПРИГЛАШЕНИЮ ПРОХОДИТ (аудит 2026-10-03).
--
-- handle_new_user при регистрации со ссылкой приглашения сразу принимал его
-- (`accepted_at`, `accepted_by_user_id`), а сторож 24.09
-- (`invitations_accept_needs_confirmed_email`) запрещает принимать
-- приглашение пользователю без подтверждённой почты. При включённом
-- подтверждении почты новый пользователь его не имеет никогда — сторож
-- бросал исключение, вставка в auth.users откатывалась, и GoTrue отвечал
-- «Database error saving new user». Ни один приглашённый не мог
-- зарегистрироваться по ссылке. Сверено прогоном в откате на боевой 03.10.
--
-- Теперь без подтверждения — обычная регистрация (свой аккаунт, как у всех с
-- 01.10), а приглашение остаётся ждать: телефон помнит его ссылку и после
-- подтверждения и входа ведёт на «Принять», где accept_invitation проверит
-- всё то же самое. С подтверждённой почтой (подтверждение выключено) — как
-- раньше, сразу.
--
-- ПРАВКА ОДНОГО УСЛОВИЯ ЖИВОГО ТЕЛА: тело берётся из базы, сверяется md5
-- (7a698d03…, 03.10), меняется ровно строка входа в ветку приглашения. Тело
-- поменяли с тех пор — миграция падает, а не затирает чужое.

do $migration$
declare
  fn regprocedure := 'public.handle_new_user()'::regprocedure;
  def text;
  old_if text := $old$  if v_invite_token <> '' then$old$;
  new_if text := $new$  -- ПОЧТА ЕЩЁ НЕ ПОДТВЕРЖДЕНА — ПРИГЛАШЕНИЕ ЖДЁТ (аудит 03.10): принять
  -- его без подтверждённой почты не даёт сторож 24.09, и регистрация по
  -- ссылке падала целиком. Без подтверждения — обычная регистрация, а
  -- приглашение примет accept_invitation после подтверждения и входа.
  if v_invite_token <> '' and new.email_confirmed_at is not null then$new$;
begin
  if (select md5(prosrc) from pg_proc where oid = fn) <> '7a698d0306557b6b3687cdec27e4da55' then
    raise exception 'handle_new_user изменилась после аудита 03.10 — перечитать тело перед правкой';
  end if;
  def := pg_get_functiondef(fn);
  if (length(def) - length(replace(def, old_if, ''))) / length(old_if) <> 1 then
    raise exception 'вход в ветку приглашения не найден ровно один раз';
  end if;
  execute replace(def, old_if, new_if);
end
$migration$;
