-- НЕДЕЛЬНОЕ РАСПИСАНИЕ МЕТКИ (владелец 2026-08-29).
--
-- «Хочу при создании метки выбрать, в какие дни недели она проставляется
--  автоматически. Надо на каждый день — выберу все дни.»
--
-- Заменяет `teams.default_city` — «одну метку на все дни сразу». Тот был
-- невидимой настройкой: день выглядел помеченным, хотя на нём ничего не
-- ставили, а снять это можно было только найдя звезду в справочнике. Из кода
-- он уже вырезан; здесь снимается и с данных.
--
-- ФОРМАТ: массив ISO-номеров дней недели, 1 = понедельник … 7 = воскресенье.
-- Пусто (`{}`) — метка не проставляется сама, только руками по датам. Это и
-- есть поведение по умолчанию, поэтому колонка NOT NULL DEFAULT '{}'.
--
-- ПОЧЕМУ МАССИВ, А НЕ СЕМЬ boolean: вопрос один — «в какие дни», — и ответ на
-- него один. Семь колонок пришлось бы синхронизировать в каждом запросе, а
-- «выбрать все» перестало бы быть одним значением.
alter table public.cities
  add column if not exists weekdays smallint[] not null default '{}';

alter table public.cities
  add constraint cities_weekdays_range
  check (weekdays <@ array[1,2,3,4,5,6,7]::smallint[]);

comment on column public.cities.weekdays is
  'Дни недели (1=Пн…7=Вс), в которые метка проставляется автоматически. Пусто — только вручную.';

-- ОСНОВНАЯ МЕТКА УХОДИТ ИЗ ДАННЫХ. Колонку не роняем: на неё мог остаться
-- ссылающийся веб-мастер, и падение записи дороже мёртвого поля. Обнуляем —
-- продукт её больше не читает, и значение только вводило бы в заблуждение
-- того, кто заглянет в базу.
update public.teams set default_city = null where default_city is not null;

comment on column public.teams.default_city is
  'НЕ ИСПОЛЬЗУЕТСЯ с 2026-08-29. Заменено на cities.weekdays. Удалить, когда веб перестанет читать.';

-- ═══ ОТЛОЖЕННОЕ УДАЛЕНИЕ: 30 ДНЕЙ ═══
--
-- Владелец 2026-08-29: «удалить — это спустя 30 дней; она уйдёт как
-- удаление, и 30 дней должно пройти, чтобы её полностью удалить».
--
-- Метка хранится СТРОКОЙ-ИМЕНЕМ в трёх местах (`day_cities.city`,
-- `teams.cities`, `clients.city`), и связи с таблицей у неё нет. Значит
-- мгновенное удаление рвёт не ссылку, а СМЫСЛ: день остаётся с именем, у
-- которого больше нет ни цвета, ни строки в справочнике. Тридцать дней —
-- это окно, в которое ошибку видно и она обратима.
alter table public.cities
  add column if not exists deleted_at timestamptz;

create index if not exists cities_deleted_at_idx
  on public.cities (tenant_id, deleted_at)
  where deleted_at is not null;

comment on column public.cities.deleted_at is
  'Помечена к удалению. Через 30 дней строка удаляется окончательно; до тех пор её можно вернуть.';
