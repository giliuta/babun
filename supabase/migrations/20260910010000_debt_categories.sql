-- СТАНДАРТНЫЕ КАТЕГОРИИ ДОЛГОВ. Третий вид справочника завела предыдущая
-- миграция, но строк в нём нет ни одной — лист «Категория долга» открывался бы
-- пустым, и первый же долг упирался бы в тупик: завести категорию можно только
-- в кабинете, а человек в этот момент заводит долг.
--
-- Список короткий нарочно. Это НЕ бухгалтерский план счетов, а семь слов,
-- которыми небольшая бригада называет, за что висят деньги; лишнее владелец
-- уберёт кнопкой «Скрыть», а своё заведёт в кабинете.
--
-- Смешивать с доходными и расходными нельзя (владелец 2026-09-10: «под расход
-- свои, под доход свои, под долги свои, они не смешиваются»): «Бензину» в
-- списке поставщиков и займов делать нечего.

-- Ключ таблицы — UNIQUE (tenant_id, slug), а Postgres считает NULL-и РАЗНЫМИ:
-- у глобальных строк tenant_id пуст, поэтому `on conflict` здесь не сработал бы
-- и повторный прогон завёл бы вторые «Поставщик» и «Займ». Защита — явное
-- «нет такого слага».
insert into public.finance_categories (tenant_id, slug, name, type, icon, color)
select null, v.slug, v.name, 'debt', v.icon, v.color
from (values
  ('debt_supplier', 'Поставщик', '📦', '#0ea5e9'),
  ('debt_client',   'Клиент',    '🙋', '#10b981'),
  ('debt_loan',     'Займ',      '🤝', '#a855f7'),
  ('debt_rent',     'Аренда',    '🏠', '#A2845E'),
  ('debt_salary',   'Зарплата',  '👤', '#f59e0b'),
  ('debt_taxes',    'Налоги',    '🧾', '#FF3B30'),
  ('debt_other',    'Иное',      '📋', '#6b7280')
) as v(slug, name, icon, color)
where not exists (
  select 1 from public.finance_categories c
  where c.slug = v.slug and c.tenant_id is null
);
