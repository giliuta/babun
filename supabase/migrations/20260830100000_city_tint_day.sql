-- ПОДСВЕЧИВАТЬ ДЕНЬ — РЕШЕНИЕ МЕТКИ, А НЕ КАЛЕНДАРЯ (владелец 2026-08-30).
--
-- «В настройках метки можно добавить тумблер: подсвечивать целый день или
--  нет. Не все дни надо подсвечивать, не все метки должны подсвечиваться.»
--
-- До сих пор заливка была ОДНА НА КАЛЕНДАРЬ — `teams.tint_days_by_label`,
-- всё или ничего. На мобильном у неё вдобавок не было переключателя вовсе:
-- код её читал, а поставить было негде. Так что это не второй тумблер рядом
-- с первым, а первый доступный — и на верном уровне: красить день или нет,
-- зависит от того, ЧТО за метка. «Кипр» стоит покрасить, «Гарантия» —
-- незачем, иначе календарь становится радугой, в которой цвет ничего не
-- значит.
--
-- ИМЯ МЕТКИ ОСТАЁТСЯ ВСЕГДА. Тумблер снимает только заливку колонки: день
-- по-прежнему подписан, просто не залит. Иначе это было бы «скрыть метку», а
-- для этого есть скрытие.
--
-- DEFAULT TRUE — у заведённых меток поведение не меняется ни на пиксель.
alter table public.cities
  add column if not exists tint_day boolean not null default true;

comment on column public.cities.tint_day is
  'Заливать ли колонку дня цветом метки в календаре. false — метка остаётся именем на дате, но день не красится.';
