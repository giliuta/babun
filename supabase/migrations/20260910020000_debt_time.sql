-- ЧАС У ДОЛГА. Владелец 2026-09-10: «время должно быть такое же, как в
-- доходе» — то есть блок времени в форме долга обязан быть тем же, что в форме
-- операции, а он печатает «день · час».
--
-- До этого у долга была только дата, и блок стоял в урезанном виде («только
-- день»): одна форма продукта отличалась от другой не по смыслу, а потому что
-- колонки не хватило. Час нужен и ленте: общая лента сортирует по дню, потом
-- по времени, и долги без часа всегда падали в конец дня, хотя случились они
-- в известную минуту.
--
-- Колонка НЕОБЯЗАТЕЛЬНАЯ: у долгов, заведённых до этой миграции, часа нет и
-- выдумывать его нельзя. Пустое время в ленте ведёт себя как раньше.
alter table public.debts
  add column if not exists occurred_time time;

comment on column public.debts.occurred_time is
  'Час возникновения долга по часам компании. NULL — час неизвестен (долги до 2026-09-10).';
