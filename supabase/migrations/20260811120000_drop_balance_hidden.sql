-- СНОС `accounts.balance_hidden` — слайс С10, «уборка»
-- (ТЗ docs/plans/ACCOUNTS-PAGE-REDESIGN-2026-08-10.md, §13 С10 и §14.8).
--
-- ⚠️ ПРИМЕНЯТЬ ТОЛЬКО ПОСЛЕ ВЫКАТА КЛИЕНТА, КОТОРЫЙ ПЕРЕСТАЛ ЕЁ ЧИТАТЬ. ⚠️
--   Клиентский код (модель `Account`, `AccountDraft`, репозиторий счетов и
--   озвучка листа оплаты инвойса) колонку больше не трогает — это сделано в
--   том же слайсе. Но у людей на телефонах ещё живёт СТАРАЯ сборка: она шлёт
--   `balance_hidden` в INSERT при создании счёта, и с момента применения этой
--   миграции такой INSERT падает целиком — человек не может завести счёт.
--   Поэтому порядок ровно один: сперва в App Store уезжает сборка без колонки,
--   и только когда старых клиентов не осталось, применяется этот файл.
--
-- ЗАЧЕМ СНОСИМ. «Глазик» и скрытие балансов выброшены владельцем 2026-08-10
--   («этот перечёркнутый глаз на хрен не нужен, мы скрывать ничего не будем»).
--   Пока колонка жива, она остаётся приглашением написать третий экран, где
--   итог иногда неполный: цифра, которая молча не всё складывает, хуже
--   отсутствия цифры — её всё равно читают как «всего».
--
-- ЧТО ЕЩЁ ЗАВИСИТ. Ничего: колонка не входит ни в один индекс, ни в одну
--   политику RLS и ни в одну функцию — слим-проекция `list_payment_accounts_safe`
--   её никогда не отдавала (см. 20260727100001_shared_accounts.sql). Поэтому
--   снос — одна строка, а не пересборка функций.

alter table public.accounts drop column if exists balance_hidden;

-- Проверка после применения: колонки нет ни в таблице, ни в чьей-либо выдаче.
do $audit$
begin
  if exists (
    select 1 from information_schema.columns
     where table_schema = 'public'
       and table_name = 'accounts'
       and column_name = 'balance_hidden'
  ) then
    raise exception 'balance_hidden всё ещё на месте';
  end if;
end
$audit$;
