-- Бакет фотографий клиентов перестаёт быть публичным.
--
-- `client-avatars` заведён публичным (20260517_007_client_avatars_bucket.sql)
-- в эпоху веба. Политики на storage.objects с тех пор ужесточили — и чтение,
-- и удаление ограничены папкой своего тенанта, — но публичность бакета живёт
-- ОТДЕЛЬНО от политик: файл по прямому адресу `/object/public/...` отдаётся
-- вообще без авторизации, и RLS его не сдерживает. Утёкшая ссылка (в письме,
-- в логе, в кэше браузера) работает вечно и не спрашивает прав.
--
-- Мобильное приложение к этому бакету не обращается ни разу, в боевой базе
-- он ПУСТ — значит гасим публичность сейчас, пока это стоит одну строку, а
-- не после того, как в нём появятся лица клиентов. Читать его дальше надо
-- подписанной ссылкой (createSignedUrl), как это уже сделано у вложений
-- клиента и фотографий записи.

update storage.buckets set public = false where id = 'client-avatars';

do $$
begin
  if exists (
    select 1 from storage.buckets where id = 'client-avatars' and public
  ) then
    raise exception 'client-avatars: бакет остался публичным';
  end if;
end $$;
