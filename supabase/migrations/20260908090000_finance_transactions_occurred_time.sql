-- Время операции (владелец 2026-09-07: «в операции выбираю дату, время,
-- категорию, сумму, заметку»). День операции хранил `occurred_on`; время
-- жило только у проводок записей (через time_start самой записи), а ручная
-- операция времени не имела и в ленте шла по времени создания. Колонка
-- необязательная: старые строки и авто-проводки остаются без времени, лента
-- по-прежнему берёт его у записи.
alter table public.finance_transactions
  add column if not exists occurred_time time;

comment on column public.finance_transactions.occurred_time is
  'Время операции по часам бизнеса (необязательно); день — occurred_on.';
