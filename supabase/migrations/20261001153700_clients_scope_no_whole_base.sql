-- «КАКИЕ КЛИЕНТЫ» — БЕЗ «ВСЕЙ БАЗЫ» (владелец 01.10).
--
-- «Если мы добавляем только к одной команде — делаем настройку только на этой
-- команде, он не может в любом случае видеть команду два… сразу открывать
-- доступ ко всей базе нельзя, надо добавлять каждой команде».
--
-- Ступень `all` у `clients.scope` открывала партнёру ВСЕХ клиентов компании,
-- поставленная в любой одной команде (`access_client_ids_in`: `bool_or(level =
-- 'all')`). Теперь у права две ступени — «Около записи» и «Своей команды», —
-- и база открывается только командами: прикрепили к команде и выставили ей
-- «Базу клиентов» — видны её клиенты; другая команда — отдельно.
--
-- Строк с `all` в базе нет (проверено 01.10), но если появятся до наката —
-- становятся «Своей команды»: это ближайшее положение, которое не шире.
-- Ветки `all` в функциях доступа остаются мёртвыми: `member_access_validate`
-- больше не пускает такую ступень, а владелец ограничений не имеет.

update public.member_access
   set level = 'own'
 where block = 'clients.scope'
   and level = 'all';

update public.access_blocks
   set levels = array['near', 'own']
 where key = 'clients.scope';
