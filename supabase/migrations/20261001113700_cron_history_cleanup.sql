-- ИСТОРИЯ ФОНОВЫХ ЗАДАЧ НЕ КОПИТСЯ (01.10, после второй заморозки базы).
--
-- pg_cron пишет строку на каждый запуск каждой задачи и не чистит их сам:
-- к 01.10 — 50 038 строк и 30 МБ из 58 МБ всей базы. На бесплатном сервере
-- (0,5 ГБ памяти на базу, вход, realtime и шлюз разом) это лишнее чтение,
-- автоочистка и место в общем кэше. Храним три дня — для разбора сбоев
-- хватает, логи сервера лежат отдельно.
--
-- Задача ставится по имени: повторный накат переписывает её, а не плодит.

delete from cron.job_run_details
 where end_time < now() - interval '3 days';

select cron.schedule(
  'cron_history_cleanup',
  '23 4 * * *',
  $$delete from cron.job_run_details where end_time < now() - interval '3 days'$$
);
