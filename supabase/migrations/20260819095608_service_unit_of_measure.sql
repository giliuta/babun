-- ДОГОН ДРЕЙФА СХЕМЫ: файл написан ЗАДНИМ ЧИСЛОМ, ровно тем же приёмом,
-- что 20260520201330_add_event_fields_to_appointments.sql.
--
-- ЧТО ЛОМАЛОСЬ. `services.unit` уехала на прод отдельно (дрейф 17-19 августа),
-- файла к версии 20260819095608 в репозитории не было — а
-- 20260820120000_drop_service_invoice_note.sql пересоздаёт
-- `list_dispatcher_services_safe()` как `language sql` и берёт в проекции
-- `'unit', s.unit`. Тела `language sql` Postgres проверяет ПРЯМО ПРИ CREATE,
-- поэтому на чистой базе цепочка обрывалась с «column s.unit does not exist».
-- Про сам факт дрейфа знали оба соседних файла: 20260820120000 в шапке — «заодно
-- возвращает в репозиторий актуальный текст RPC с team_id и unit», 20260821120000
-- в шапке — «Колонка services.unit прожила два дня (20260819095608)». Но колонку
-- так никто и не завёл. (Ссылки на соседей — по именам файлов и по цитате, а не
-- по номерам строк: номера уезжают от первой же правки.)
--
-- ПОЧЕМУ ЭТА ВЕРСИЯ, А НЕ СВЕЖАЯ. Версия 20260819095608 названа в комментарии
-- соседней миграции как та, что колонку добавила, то есть на проде она уже
-- записана в supabase_migrations.schema_migrations. `supabase db push` сверяет
-- ПО ВЕРСИИ и на проде файл пропустит; на чистой базе он встанет между
-- 20260817195637 (services.team_id) и 20260820120000 — как раз перед
-- читателем. Свежая метка легла бы ПОСЛЕ него и ничего бы не починила.
--
-- ИМЯ ФАЙЛА = ИМЯ НА ПРОДЕ. Хвост после версии называется ровно так, как эта
-- миграция записана в supabase_migrations на проде — `service_unit_of_measure`
-- (зафиксировано в docs/audit/SERVICES-PAGE-AUDIT-2026-08-21.md и в шапке
-- 20260817195637). Накат сверяется по версии, а не по имени, так что на
-- повторное применение имя не влияет — но человек, который сравнит `supabase
-- migration list` с содержимым папки, должен видеть одну и ту же строку, а не
-- гадать, один это файл или два разных.
--
-- КОЛОНКА ЖИВЁТ НЕДОЛГО И ЭТО НОРМАЛЬНО. Через два файла её сносит
-- 20260821120000_drop_service_unit.sql («единицы измерения у услуги нет»),
-- а 20260825100000_service_unit_and_price_entry.sql заводит заново — уже
-- осознанно, вместе со строкой счёта. Итоговая схема от этого файла не
-- меняется; он существует ради того, чтобы промежуточные миграции вообще
-- смогли примениться.

alter table public.services
  add column if not exists unit text;

comment on column public.services.unit is
