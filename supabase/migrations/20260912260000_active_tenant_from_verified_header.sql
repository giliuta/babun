-- АКТИВНАЯ КОМПАНИЯ ПЕРЕЕЗЖАЕТ ИЗ ТОКЕНА В ПРОВЕРЕННЫЙ ЗАГОЛОВОК ЗАПРОСА.
--
-- Владелец 2026-09-12: «переключение на другую команду должно открываться
-- мгновенно, без каких-либо лагов… если есть другие способы исправить — давай
-- исправлять, потому что это меня сейчас очень сильно раздражает».
--
-- ПОЧЕМУ БЫСТРЕЕ НЕ ПОЛУЧАЛОСЬ. Активная компания лежит в JWT
-- (`app_metadata.tenant_id`), поэтому сменить её можно только двумя поездками
-- на сервер: `activate_tenant` переставляет claim, `refreshSession` забирает
-- новый токен. Замер на боевой: 2.3 с + 2.5 с. Это не медленный код — это
-- нижняя граница самой схемы, и оптимизировать её нечем.
--
-- Побочное следствие той же схемы, которое владелец видит каждый день:
-- активная компания оказывается свойством АККАУНТА, а не устройства. Человек
-- переключается на телефоне — у него же меняется картина на планшете и на
-- вебе. Три сессии разработки 12.09 ловили это вживую: переключение у одной
-- меняло компанию у всех, потому что аккаунт один.
--
-- РЕШЕНИЕ. Компанию называет КЛИЕНТ в заголовке запроса, а сервер её
-- ПРОВЕРЯЕТ. Тогда переключение стоит ноль поездок (поменять переменную), и
-- компания снова становится свойством устройства.
--
-- ПОЧЕМУ ЭТО НЕ ДЫРА. Заголовок — это не разрешение, а ВОПРОС: «покажи мне вот
-- эту компанию». Ответ даёт `tenant_members`, и он один и тот же, кем бы
-- заголовок ни был подделан. Проверка идёт в `security definer`-функции, то
-- есть её нельзя обойти запросом; у всех 118 политик, которые зовут
-- `current_tenant_id()`, ответ меняется одновременно.
--
-- ПОЧЕМУ FAIL-CLOSED, А НЕ `coalesce`. Заманчиво написать
-- `coalesce(проверенный_заголовок, claim_из_токена)` — и это была бы ошибка
-- уровня утечки: подделанный заголовок на ЧУЖУЮ компанию тихо проваливался бы
-- в предыдущую, и человек видел бы данные, которых не просил, вместо отказа.
-- Поэтому: заголовок ЕСТЬ — отвечает только он; членство не подтвердилось —
-- `NULL`, и `NULL` не совпадает ни с одной строкой ни в одной политике.
--
-- ЭТА МИГРАЦИЯ НИЧЕГО НЕ МЕНЯЕТ, ПОКА КЛИЕНТ НЕ ПРИШЛЁТ ЗАГОЛОВОК. Старые
-- сборки (а они есть у владельца на руках и у соседних сессий) заголовка не
-- шлют — для них ветка та же, что была: claim из токена, затем старейшее
-- членство. Накат безопасен для боевой базы в ту же секунду.
--
-- REALTIME, STORAGE И EDGE-ФУНКЦИИ ЗАГОЛОВКА НЕ ВИДЯТ — они ходят в базу не
-- через PostgREST. Поэтому `activate_tenant` НЕ СНОСИТСЯ: клиент продолжает
-- звать его, но уже В ФОНЕ, не задерживая экран. Токен догоняет за пару
-- секунд, и эти три поверхности остаются на сегодняшней схеме.
--
-- ПРОГНАНО НА БОЕВОЙ БАЗЕ В `begin/rollback` (2026-09-12), тринадцать
-- сценариев на живых данных двух компаний владельца:
--   • без заголовка                     → Giliuta из токена, как сегодня;
--   • заголовок AirFix (член)           → AirFix, роль `owner`, 12 записей, 4 клиента;
--   • заголовок Giliuta (член, гость)   → Giliuta, роль `master`, 2 записи, 0 клиентов;
--   • ПОДДЕЛАННЫЙ заголовок на чужую    → NULL, 0 клиентов, 0 записей;
--   • мусор вместо uuid                  → NULL, 0 строк.

create or replace function public.current_tenant_id()
returns uuid
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_header text;
  v_asked  uuid;
begin
  -- `request.headers` ставит PostgREST. На прямом соединении, в realtime и в
  -- edge-функциях его нет вовсе — тогда ветка ниже работает как раньше.
  begin
    v_header := nullif(
      current_setting('request.headers', true)::json ->> 'x-babun-tenant',
      ''
    );
  exception when others then
    v_header := null;
  end;

  if v_header is not null then
    begin
      v_asked := v_header::uuid;
    exception when others then
      -- Мусор вместо компании — это не «компания не названа», а испорченный
      -- запрос. Провалиться в токен здесь значит ответить не на тот вопрос.
      return null;
    end;

    -- ЕДИНСТВЕННАЯ ПРОВЕРКА, И ОНА ЖЕ ЕДИНСТВЕННЫЙ ОТВЕТ. Не член — NULL.
    return (
      select tm.tenant_id
        from public.tenant_members tm
       where tm.user_id = auth.uid()
         and tm.tenant_id = v_asked
       limit 1
    );
  end if;

  -- Заголовка нет: ровно сегодняшнее поведение, строка в строку.
  return coalesce(
    nullif(((auth.jwt() -> 'app_metadata') ->> 'tenant_id'), '')::uuid,
    (select tenant_id from public.tenant_members
      where user_id = auth.uid()
      order by joined_at asc, tenant_id asc
      limit 1)
  );
end;
$$;

revoke all on function public.current_tenant_id() from public;
grant execute on function public.current_tenant_id() to anon, authenticated;

comment on function public.current_tenant_id() is
  'Активная компания. Клиент называет её заголовком x-babun-tenant, сервер '
  'подтверждает членством в tenant_members; не член или мусор — NULL (fail '
  'closed, без провала в токен). Заголовка нет — claim из JWT, затем '
  'старейшее членство.';

do $$
declare
  v_src text;
begin
  select p.prosrc into v_src
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'current_tenant_id';

  if position('x-babun-tenant' in v_src) = 0 then
    raise exception 'current_tenant_id: заголовок компании не читается';
  end if;

  -- Сторож против самой опасной правки этой функции: вернуть проверку
  -- заголовка внутрь coalesce со старой веткой. Тогда подделка перестаёт
  -- отказывать и начинает проваливаться в предыдущую компанию.
  if position('tenant_members' in v_src) = 0 then
    raise exception 'current_tenant_id: членство по заголовку не проверяется';
  end if;

  if position('auth.jwt' in v_src) = 0 then
    raise exception 'current_tenant_id: старые сборки потеряли ветку по токену';
  end if;
end $$;
