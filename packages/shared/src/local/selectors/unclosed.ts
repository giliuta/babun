import type { Appointment } from "../appointments";

// НЕ ЗАКРЫТО — ДЕНЬГИ, КОТОРЫХ НЕТ НИ В ОДНОЙ ЦИФРЕ.
//
// Прошедший визит, по которому бригадир не сказал ни «выполнено», ни «не
// состоялось», проваливается мимо всех сводок: «Долги» считают только
// завершённые визиты, «Документы» — только выставленные инвойсы, «Доход» —
// только проведённые оплаты. Работа сделана (или не сделана), а в отчётах её
// нет, и прибыль тихо занижена ровно на эту сумму.
//
// Формула жила копией в трёх экранах (список незакрытых, хаб кабинета,
// закрытие дня). Три копии одной правды — это три будущих расхождения.

/** Прошедшие рабочие записи, оставшиеся в статусе «Запланирована». */
export function unclosedAppointments(
  appts: readonly Appointment[],
  todayYmd: string,
): Appointment[] {
  return appts
    .filter(
      (a) =>
        // События и личные дела закрывать нечем — у них нет исхода.
        (a.kind === undefined || a.kind === "work") &&
        a.status === "scheduled" &&
        a.date < todayYmd,
    )
    .sort((a, b) => b.date.localeCompare(a.date));
}

/** Сумма под вопросом: столько заработано или потеряно — пока неизвестно. */
export function unclosedTotal(appts: readonly Appointment[]): number {
  return appts.reduce((sum, a) => sum + (a.total_amount ?? 0), 0);
}
