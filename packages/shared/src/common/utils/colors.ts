// ЦВЕТ СУЩНОСТИ НЕ ДОЛЖЕН СОВПАДАТЬ С ЦВЕТОМ СМЫСЛА (2026-08-12).
// В продукте цвет уже занят: зелёный — приход, красный — расход и долг,
// кобальт — действие, янтарь — внимание. Команда, покрашенная в смысл,
// врёт цветом: на экране счетов красный чип команды стоит рядом с красной
// суммой долга, и один пигмент несёт два несовместимых сообщения в одном
// вьюпорте.
//
// Правило: оттенок палитры обязан отстоять больше чем на 15° по кругу от
// danger (#C9372C, hue 4°) и success (#087A52, hue 159°). Померено по всем
// значениям: под запрет попал ровно один — «Красный» #FF3B30 (hue 3°,
// дистанция 1°), он и убран. «Розовый» #FF2D55 (349°, дистанция 16°) и
// «Зелёный» #34C759 (135°, дистанция 24°) остаются: это соседи смысла, а не
// он сам, и палитра без единого тёплого красного и без зелёного перестала бы
// покрывать метки и услуги.
//
// Существующие данные тенантов НЕ МИГРИРУЮТСЯ: у команды, покрашенной в
// #FF3B30 раньше, цвет остаётся её цветом — просто новый такой не выбрать.

