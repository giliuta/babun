//
// Зеркало («Посмотреть его глазами», STORY-083) показывает владельцу
// НАСТОЯЩИЕ экраны продукта с правами сотрудника — и владелец их тыкает,
// ровно как просил 20.09: «протыкать так сказать». Беда в том, что запросы
// всё это время уходят ЕГО токеном: кнопка, которую в зеркале видно, при
// нажатии создаёт настоящую запись в боевой базе. Предпросмотр, который
// молча создаёт данные, — худший вид предпросмотра.
//
// ДВЕ ДОРОГИ У ЗАПИСИ, И ВТОРАЯ ОПАСНЕЕ. Прямой запрос к серверу отбить
// легко (обёртка `fetch` в приложении). Но клиенты и записи пишутся
// офлайн-первыми: операция сначала ложится в очередь на устройстве, а
// уезжает потом — то есть тап в зеркале создал бы отложенную запись,
// которая уйдёт в базу УЖЕ ПОСЛЕ выхода из режима, когда и связать её будет
// не с чем. Поэтому засов стоит и на входе в очередь (`queue-events.ts`).
//
// Засов — процессный, как и умолчания реплеера рядом: обёртки кэша ничего не
// знают о приложении и спросить React-контекст не могут.

/** Запись, отбитая засовом. Отдельный тип — чтобы приложение отличило её от
 *  сетевой ошибки и сказало человеку правду, а не «проверьте соединение».
 *
 *  СООБЩЕНИЕ — ЧЕЛОВЕЧЕСКОЕ, И ЭТО НЕ УКРАШЕНИЕ. Экраны с собственным
 *  разбором ошибок печатают `error.message` как есть; пока в нём стоял адрес
 *  функции, владелец читал «Запись отбита: https://…/rpc/create_client_with_tags»
 *  (проверено глазами 20.09). Технические подробности живут в `detail`. */
export class WritesBlockedError extends Error {
  /** Узнаётся без `instanceof`: модуль может оказаться в двух копиях
   *  (приложение и общий пакет), и проверка по прототипу тогда врёт. */
  readonly writesBlocked = true;

  /** Что именно пытались записать — для отчёта и отладки, не для экрана. */
  readonly detail: string;

  constructor(what: string) {
    super("Это просмотр чужими глазами — менять здесь нельзя. Выйдите из просмотра, чтобы работать.");
    this.detail = what;
    this.name = "WritesBlockedError";
  }
}

export function isWritesBlockedError(error: unknown): boolean {
  return (
    typeof error === "object" &&
    error !== null &&
    (error as { writesBlocked?: unknown }).writesBlocked === true
  );
}

/** По умолчанию засова нет: обычная работа приложения ничего не замечает. */
let blocked: () => boolean = () => false;

/** Приложение объявляет, когда запись запрещена. Живая функция, а не флаг:
 *  режим включается и выключается на ходу, а модуль читается один раз. */
export function setWriteGuard(fn: () => boolean): void {
  blocked = fn;
}

export function writesBlocked(): boolean {
  return blocked();
}

/** Бросает, если запись сейчас запрещена. `what` попадает в текст ошибки и
 *  в отчёт: по нему видно, какая именно дорога попыталась писать. */
export function assertWritesAllowed(what: string): void {
  if (blocked()) throw new WritesBlockedError(what);
}

/** ТОЛЬКО ДЛЯ ТЕСТОВ: вернуть засов в исходное «записывать можно». */
export function __resetWriteGuardForTests(): void {
  blocked = () => false;
}
